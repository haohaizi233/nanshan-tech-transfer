def main() -> None:
    with get_cursor(commit=True) as cur:
        cur.execute(
            """
            SELECT id, registration_status, status, registered_by_user_id
            FROM institution
            WHERE name = %s
            """,
            (ORG_NAME,),
        )
        org = cur.fetchone()
        if not org or org["registration_status"] != "approved" or org["status"] != "active":
            raise RuntimeError(f"未找到已认证且启用的机构：{ORG_NAME}")

        if org["registered_by_user_id"] != PUBLISHER_USER_ID:
            raise RuntimeError("机构登记人与预期发布人不一致，已停止写入")

        cur.execute("SELECT user_id, phone, email, wechat FROM user_profile WHERE user_id = %s", (PUBLISHER_USER_ID,))
        publisher = cur.fetchone()
        if not publisher:
            raise RuntimeError("未找到机构登记人的个人资料，已停止写入")

        cur.execute("SELECT title FROM demand WHERE org_id = %s", (org["id"],))
        existing_titles = {row["title"] for row in cur.fetchall()}
        missing = [item for item in DEMANDS if item[0] not in existing_titles]

        today = date.today()
        rows = []
        for index, (title, scene, min_budget, max_budget, months, category_id) in enumerate(missing):
            published_on = today - timedelta(days=2 + (index * 3) % 88)
            description = (
                f"恒程创新现面向产业化应用征集合作伙伴。{scene}"
                "项目计划采用联合研发与技术服务相结合的方式推进，优先考虑具有同类项目交付经验、"
                "可提供实施团队及后续运维支持的高校、科研院所和科技企业。"
            )
            rows.append((
                PUBLISHER_USER_ID, PUBLISHER_USER_ID, title, category_id, org["id"], ORG_NAME,
                description, "广东省深圳市南山区", Json(["联合研发", "技术服务"]),
                min_budget, max_budget, False, published_on + timedelta(days=months * 30),
                f"计划在{months}个月内完成项目交付", "李四", "技术合作负责人",
                publisher["phone"], publisher["email"], publisher["wechat"],
                "published", published_on, published_on, published_on,
            ))

        if rows:
            execute_values(
                cur,
                """
                INSERT INTO demand (
                    owner_user_id, created_by_user_id, title, category_id, org_id, org_name_snapshot,
                    description, region, coop_mode, budget_min_wan, budget_max_wan, budget_negotiable,
                    expect_deadline, deadline_desc, contact_name, contact_title, contact_phone,
                    contact_email, contact_wechat, status, published_at, created_at, updated_at
                ) VALUES %s
                """,
                rows,
                template="(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            )

        cur.execute(
            "SELECT COUNT(*) AS count FROM demand WHERE org_id = %s AND status = 'published' AND deleted_at IS NULL",
            (org["id"],),
        )
        total = cur.fetchone()["count"]
        print(f"机构：{ORG_NAME}（ID {org['id']}）")
        print(f"本次插入：{len(rows)} 条；当前已发布需求：{total} 条")


if __name__ == "__main__":
    main()
