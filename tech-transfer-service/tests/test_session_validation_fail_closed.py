def test_f01_to_f07_f12_to_f16_session_validation_fail_closed(pg_env):
    """覆盖 F01-F07, F12-F16：正常/不存在/注销/过期/归属不匹配/版本变化/非法UUID/旧Token/吊销与跨Worker一致性。"""
    schema, client = pg_env
    sid_u1 = _seed_user(schema, 1001, email="u1001@qq.com", session_version=1)
    sid_u2 = _seed_user(schema, 1002, email="u1002@qq.com", session_version=1)
    now_epoch = int(time.time())

    # F01: 正常有效 SID
    tok_valid = sign_access_token(1001, "U1001", ["user"], 1, sid=sid_u1, auth_time=now_epoch)
    res_f01 = validate_session_state(1001, sid_u1, 1)
    assert res_f01.state == SessionValidationState.ACTIVE
    assert identity(_http_request(tok_valid))["userId"] == 1001
    assert (
        client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_valid}"}).status_code
        == 200
    )

    # F02: 不存在的新版 SID -> NOT_FOUND -> 401（绝不返回 ACTIVE 或降级 LEGACY）
    missing_sid = str(uuid.uuid4())
    tok_missing = sign_access_token(1001, "U1001", ["user"], 1, sid=missing_sid, auth_time=now_epoch)
    res_f02 = validate_session_state(1001, missing_sid, 1)
    assert res_f02.state == SessionValidationState.NOT_FOUND
    assert _session_is_active(1001, missing_sid) is False
    with pytest.raises(BizError) as exc_f02:
        identity(_http_request(tok_missing))
    assert exc_f02.value.http_status == 401
    assert (
        client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_missing}"}).status_code
        == 401
    )

    # F03: 已注销 SID -> REVOKED -> 401
    revoked_sid = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, sid, auth_time, revoked_at) "
            "VALUES (1001, %s, 'revoked', %s, NOW(), NOW())",
            (uuid.uuid4().hex, revoked_sid),
        )
    tok_revoked = sign_access_token(1001, "U1001", ["user"], 1, sid=revoked_sid, auth_time=now_epoch)
    assert validate_session_state(1001, revoked_sid, 1).state == SessionValidationState.REVOKED
    assert (
        client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_revoked}"}).status_code
        == 401
    )

    # F04: 过期 SID -> EXPIRED -> 401
    expired_sid = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, sid, auth_time, expires_at) "
            "VALUES (1001, %s, 'active', %s, NOW() - INTERVAL '8 days', NOW() - INTERVAL '1 minute')",
            (uuid.uuid4().hex, expired_sid),
        )
    tok_expired = sign_access_token(1001, "U1001", ["user"], 1, sid=expired_sid, auth_time=now_epoch)
    assert validate_session_state(1001, expired_sid, 1).state == SessionValidationState.EXPIRED
    assert (
        client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_expired}"}).status_code
        == 401
    )

    # F05: SID 与 user_id 不匹配 -> NOT_FOUND -> 401
    tok_mismatch_user = sign_access_token(1001, "U1001", ["user"], 1, sid=sid_u2, auth_time=now_epoch)
    assert validate_session_state(1001, sid_u2, 1).state == SessionValidationState.NOT_FOUND
    assert (
        client.get(
            "/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_mismatch_user}"}
        ).status_code
        == 401
    )

    # F06: session_version 不匹配 -> REVOKED -> 401
    tok_stale_ver = sign_access_token(1001, "U1001", ["user"], 99, sid=sid_u1, auth_time=now_epoch)
    assert validate_session_state(1001, sid_u1, 99).state == SessionValidationState.REVOKED
    assert (
        client.get(
            "/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_stale_ver}"}
        ).status_code
        == 401
    )

    # F07: 非法 UUID SID -> 在查询数据库之前即拒绝（INVALID -> 401，zero DB calls）
    spy_cur = MagicMock()
    for bad_sid in ("not-a-uuid", "", "   ", 12345):
        res_f07 = validate_session_state(1001, bad_sid, 1, cur=spy_cur)
        assert res_f07.state == SessionValidationState.INVALID
        spy_cur.execute.assert_not_called()
    bad_tok = sign_access_token(1001, "U1001", ["user"], 1, sid="not-a-uuid", auth_time=now_epoch)
    with pytest.raises(BizError) as exc_f07:
        identity(_http_request(bad_tok))
    assert exc_f07.value.http_status == 401

    # F12 & F13: 历史 Token（无 SID）普通接口允许但无 recent_auth 资格，且敏感高风险操作 401 拒绝
    tok_legacy = sign_access_token(1002, "U1002", ["user"], 1, sid=None, auth_time=now_epoch)
    res_f12 = validate_session_state(1002, None, 1)
    assert res_f12.state == SessionValidationState.LEGACY
    assert (
        client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_legacy}"}).status_code
        == 200
    )
    assert "recent_auth" not in get_available_step_up_methods(1002, auth_time=now_epoch, has_sid=False)
    r_f13 = client.post(
        "/api/tech-transfer/v1/me/security/step-up/verify",
        headers={"Authorization": f"Bearer {tok_legacy}"},
        json={
            "purpose": "rebind_email",
            "method": "password",
            "currentPassword": "InitPass!2026",
            "targetContact": "new1002@qq.com",
        },
    )
    assert r_f13.status_code == 401
    legacy_ctx = session_context_from_request(_http_request(tok_legacy), 1002)
    with pytest.raises(BizError) as exc_f13_ch:
        start_step_up_challenge(
            1002,
            "rebind_email",
            "old_email_otp",
            SimpleNamespace(ip="192.0.2.1", device_id="d1", request_id="r1"),
            target_contact="new1002@qq.com",
            session_ctx=legacy_ctx,
        )
    assert exc_f13_ch.value.http_status == 401

    # F14 & F15: 会话注销后既不能签发 Step-up Grant，也不能消费先前签发的 Grant
    login_u3 = password_login_session("user_1001", "InitPass!2026")
    tok_u3 = login_u3["accessToken"]
    rt_u3 = login_u3["refreshToken"]
    ctx_u3 = session_context_from_request(_http_request(tok_u3), 1001)
    assert ctx_u3 is not None and ctx_u3.sid
    grant_before_logout = issue_step_up_grant(
        1001,
        purpose="rebind_email",
        method="password",
        session_fingerprint=ctx_u3.fingerprint_for_purpose("rebind_email"),
        session_ctx=ctx_u3,
        current_password="InitPass!2026",
        target_contact="afterlogout@qq.com",
    )["stepUpGrant"]

    # F16: 模拟 Worker A 本地 auth_cache 已热缓存该用户状态，Worker B 跨实例注销后 Worker A 未收到本地缓存清理仍即时失效
    _user_session_version(1001)
    cached_snapshot = dict(auth_cache._cache)
    logout_session(rt_u3)
    # 恢复注销前 Worker A 本地热点缓存快照，验证现代 SID 不受跨 Worker 本地缓存延迟影响
    auth_cache._cache.update(cached_snapshot)
    assert (
        client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok_u3}"}).status_code
        == 401
    )

    # F14: 注销后禁止再签发 Grant
    with pytest.raises(BizError) as exc_f14:
        issue_step_up_grant(
            1001,
            purpose="rebind_email",
            method="password",
            session_fingerprint=ctx_u3.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx_u3,
            current_password="InitPass!2026",
            target_contact="afterlogout2@qq.com",
        )
    assert exc_f14.value.http_status == 401

    # F15: 注销前签发的 Grant 在注销后消费必须被拒且标记为 revoked
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        with pytest.raises(BizError) as exc_f15:
            validate_step_up_grant(
                cur,
                user_id=1001,
                grant_token=grant_before_logout,
                purpose="rebind_email",
                session_fingerprint=ctx_u3.fingerprint_for_purpose("rebind_email"),
                session_ctx=ctx_u3,
                target_contact="afterlogout@qq.com",
                consume=True,
            )
        assert exc_f15.value.http_status in (401, 403)
    with pytest.raises(BizError) as exc_f15_bind:
        from modules.security.email_gateway import start_email_binding

        start_email_binding(
            1001,
            "afterlogout@qq.com",
            SimpleNamespace(ip="192.0.2.15", device_id="d15", request_id="r15"),
            step_up_grant=grant_before_logout,
            session_ctx=ctx_u3,
        )
    assert exc_f15_bind.value.http_status in (401, 403)


def test_f08_to_f11_db_failures_and_missing_schema_fail_closed_503(pg_env):
    """覆盖 F08-F11：数据库连接失败、查询超时、缺表(UndefinedTable)、缺字段(UndefinedColumn) 全部返回 UNAVAILABLE / 503。"""
    schema, client = pg_env
    sid_u1 = _seed_user(schema, 2001, session_version=1)
    tok = sign_access_token(2001, "U2001", ["user"], 1, sid=sid_u1, auth_time=int(time.time()))

    class _TimeoutError(psycopg2.OperationalError):
        pgcode = "57014"

    faults = [
        ("F08", psycopg2.OperationalError("connection to server refused")),
        ("F09", _TimeoutError("canceling statement due to statement timeout")),
        ("F10", psycopg2.errors.UndefinedTable('relation "auth_session" does not exist')),
        ("F11", psycopg2.errors.UndefinedColumn("column s.sid does not exist")),
    ]
    for fid, exc in faults:
        bad_cur = MagicMock()
        bad_cur.execute.side_effect = exc
        res = validate_session_state(2001, sid_u1, 1, cur=bad_cur)
        assert res.state == SessionValidationState.UNAVAILABLE, fid
        with pytest.raises(BizError) as biz_exc:
            raise_for_session_state(res)
        assert biz_exc.value.http_status == 503, fid

        # 中间件 identity() 与 _session_is_active / _user_session_version 均必须 503，严禁返回 True/1/401
        @contextmanager
        def _broken_cursor(commit: bool = False):
            yield bad_cur

        with patch("db.get_cursor", _broken_cursor):
            with pytest.raises(BizError) as mid_exc:
                identity(_http_request(tok))
            assert mid_exc.value.http_status == 503, fid
            with pytest.raises(BizError) as act_exc:
                _session_is_active(2001, sid_u1)
            assert act_exc.value.http_status == 503, fid
            with pytest.raises(BizError) as ver_exc:
                _user_session_version(2001)
            assert ver_exc.value.http_status == 503, fid
            resp = client.get("/api/tech-transfer/v1/me/security", headers={"Authorization": f"Bearer {tok}"})
            assert resp.status_code == 503, fid

    # 真实 PostgreSQL SQL 验证缺列(UndefinedColumn) 与缺表(UndefinedTable)
    bad_schema = f"sess_broken_{uuid.uuid4().hex[:8]}"
    conn = psycopg2.connect(PG_DSN)
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(bad_schema)))
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(bad_schema)))
            _apply_sql(cur, bad_schema, _BASE_TABLES_SQL)
            cur.execute("ALTER TABLE app_user ADD COLUMN session_version INT NOT NULL DEFAULT 1")
            cur.execute(
                "INSERT INTO app_user (id, user_no, status, session_version) VALUES (2001, 'U2001', 'active', 1)"
            )

        with _schema_cursor(PG_DSN, bad_schema, commit=False) as bcur:
            # 缺少 auth_session.sid 列 -> UndefinedColumn -> UNAVAILABLE (503)
            res_col = validate_session_state(2001, sid_u1, 1, cur=bcur)
            assert res_col.state == SessionValidationState.UNAVAILABLE
        with _schema_cursor(PG_DSN, bad_schema, commit=True) as bcur:
            bcur.execute("DROP TABLE auth_session")
        with _schema_cursor(PG_DSN, bad_schema, commit=False) as bcur:
            # 缺少 auth_session 表 -> UndefinedTable -> UNAVAILABLE (503)
            res_tbl = validate_session_state(2001, sid_u1, 1, cur=bcur)
            assert res_tbl.state == SessionValidationState.UNAVAILABLE
    finally:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(bad_schema)))
        conn.close()
