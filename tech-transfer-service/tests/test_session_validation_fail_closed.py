def _apply_sql(cur, schema: str, raw_sql: str) -> None:
    cur.execute(raw_sql.replace("public.", f"{schema}."))


@contextmanager
def _schema_cursor(dsn: str, schema: str, commit: bool = False):
    conn = psycopg2.connect(dsn, cursor_factory=RealDictCursor)
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            yield cur
        if commit:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _http_request(token: str) -> Request:
    return Request(
        {
            "type": "http",
            "method": "GET",
            "path": "/api/tech-transfer/v1/me/security",
            "headers": [(b"authorization", f"Bearer {token}".encode("latin-1"))],
        }
    )


def _seed_user(schema: str, uid: int, *, email: str | None = None, session_version: int = 1) -> str:
    sid = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO app_user (id, user_no, status, session_version) VALUES (%s, %s, 'active', %s)",
            (uid, f"U{uid}", session_version),
        )
        cur.execute(
            "INSERT INTO user_credential (user_id, username, password_hash, password_configured, status) "
            "VALUES (%s, %s, %s, true, 'active')",
            (uid, f"user_{uid}", hash_password("InitPass!2026")),
        )
        cur.execute("INSERT INTO user_profile (user_id, display_name) VALUES (%s, %s)", (uid, f"User{uid}"))
        cur.execute("INSERT INTO user_role (user_id, role_code) VALUES (%s, 'user')", (uid,))
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, sid, auth_time, expires_at) "
            "VALUES (%s, %s, 'active', %s, NOW(), NOW() + INTERVAL '7 days')",
            (uid, uuid.uuid4().hex, sid),
        )
        if email:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'email', %s, NOW(), 'active', 'email')",
                (uid, email),
            )
    return sid


