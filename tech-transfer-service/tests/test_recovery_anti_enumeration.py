def _seed_user_with_email(schema: str, uid: int, email: str, *, disabled: bool = False) -> None:
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO app_user (id, user_no, status) VALUES (%s, %s, %s)",
            (uid, f"U{uid}", "disabled" if disabled else "active"),
        )
        cur.execute(
            "INSERT INTO user_credential (user_id, username, password_hash, password_configured, status) "
            "VALUES (%s, %s, %s, true, 'active')",
            (uid, f"u{uid}", hash_password("InitPass!123")),
        )
        cur.execute(
            "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
            "VALUES (%s, 'email', %s, NOW(), 'active', 'email')",
            (uid, email),
        )


def _insert_challenge(
    schema: str,
    cid: str,
    uid: int,
    email: str,
    code: str,
    *,
    purpose: str = "password_recovery",
    status: str = "pending",
    send_state: str = "accepted",
    expires_offset_sql: str = "INTERVAL '5 minutes'",
    attempt_count: int = 0,
    max_attempts: int = 5,
    override_dest_fp: str | None = None,
) -> None:
    fp = override_dest_fp or _fingerprint(email)
    chash = _hmac_code_v2(cid, purpose, "email_otp", email, code)
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            f"""
            INSERT INTO auth_challenge(
                id, user_id, purpose, channel, destination_fingerprint, destination_masked,
                code_hash, status, attempt_count, max_attempts, expires_at, send_request_id,
                send_state, code_hash_version
            ) VALUES (
                %s, %s, %s, 'email_otp', %s, 'u***@qq.com',
                %s, %s, %s, %s, NOW() + {expires_offset_sql}, %s, %s, 2
            )
            """,
            (cid, uid, purpose, fp, chash, status, attempt_count, max_attempts, cid, send_state),
        )


def test_all_anonymous_recovery_verify_failures_return_identical_public_response(pg_schema, caplog):
    caplog.set_level(logging.INFO, logger="nanshan.security")
    _seed_user_with_email(pg_schema, 1, "u1@qq.com", disabled=False)
    _seed_user_with_email(pg_schema, 2, "u2@qq.com", disabled=True)
    _seed_user_with_email(pg_schema, 3, "u3@qq.com", disabled=False)
    _seed_user_with_email(pg_schema, 4, "u4@qq.com", disabled=False)

    c_wrong = str(uuid.uuid4())
    c_expired = str(uuid.uuid4())
    c_locked = str(uuid.uuid4())
    c_consumed = str(uuid.uuid4())
    c_cancelled = str(uuid.uuid4())
    c_rejected = str(uuid.uuid4())
    c_bind = str(uuid.uuid4())
    c_inelig = str(uuid.uuid4())
    c_changed = str(uuid.uuid4())
    c_missing = str(uuid.uuid4())

    _insert_challenge(pg_schema, c_wrong, 1, "u1@qq.com", "111222", attempt_count=4, max_attempts=5)
    _insert_challenge(pg_schema, c_expired, 3, "u3@qq.com", "111222", expires_offset_sql="INTERVAL '-10 seconds'")
    _insert_challenge(pg_schema, c_locked, 1, "u1@qq.com", "111222", status="locked", attempt_count=5)
    _insert_challenge(pg_schema, c_consumed, 1, "u1@qq.com", "111222", status="consumed")
    _insert_challenge(pg_schema, c_cancelled, 1, "u1@qq.com", "111222", status="cancelled")
    _insert_challenge(pg_schema, c_rejected, 1, "u1@qq.com", "111222", status="failed", send_state="rejected")
    _insert_challenge(pg_schema, c_bind, 1, "u1@qq.com", "111222", purpose="bind_email")
    _insert_challenge(pg_schema, c_inelig, 2, "u2@qq.com", "111222")
    _insert_challenge(
        pg_schema,
        c_changed,
        4,
        "u4@qq.com",
        "111222",
        override_dest_fp=_fingerprint("previous@qq.com"),
    )

    probes = [
        ("CHALLENGE_NOT_FOUND", c_missing, "111222"),
        ("CHALLENGE_EXPIRED", c_expired, "111222"),
        ("CHALLENGE_LOCKED", c_locked, "111222"),
        ("CHALLENGE_CONSUMED", c_consumed, "111222"),
        ("CHALLENGE_CANCELLED", c_cancelled, "111222"),
        ("DELIVERY_REJECTED", c_rejected, "111222"),
        ("PURPOSE_MISMATCH", c_bind, "111222"),
        ("ACCOUNT_INELIGIBLE", c_inelig, "111222"),
        ("CONTACT_CHANGED", c_changed, "111222"),
        ("CODE_MISMATCH", c_wrong, "000000"),
    ]

    snapshots = []
    for _reason, cid, code in probes:
        resp = client.post("/api/tech-transfer/v1/auth/recovery/verify", json={"challengeId": cid, "code": code})
        body = resp.json()
        assert resp.status_code == 400
        assert body["code"] == TT_AUTH_RECOVERY_INVALID[0]
        assert body["message"] == TT_AUTH_RECOVERY_INVALID[1]
        assert set(body.keys()) == {"code", "message", "requestId"}
        assert "details" not in body
        snapshots.append((resp.status_code, body["code"], body["message"], tuple(sorted(body.keys()))))

    assert len(set(snapshots)) == 1

    # 1. 错误尝试在独立提交事务后仍递增 attempt_count 并达到上限后锁定
    with _schema_cursor(PG_DSN, pg_schema, commit=False) as cur:
        cur.execute("SELECT status, attempt_count FROM auth_challenge WHERE id = %s", (c_wrong,))
        wrong_row = cur.fetchone()
        assert wrong_row["attempt_count"] == 5
        assert wrong_row["status"] == "locked"

        # 2. 不存在的 challengeId 绝不产生数据库写入
        cur.execute("SELECT COUNT(*) AS cnt FROM auth_challenge WHERE id = %s", (c_missing,))
        assert cur.fetchone()["cnt"] == 0
        cur.execute("SELECT COUNT(*) AS cnt FROM recovery_grant")
        assert cur.fetchone()["cnt"] == 0

    # 3. 内部运维日志与指标仍可清晰区分不同失败原因，且绝不含明文挑战码或邮箱
    combined_logs = "\n".join(caplog.messages)
    assert "internal_reason=CHALLENGE_NOT_FOUND" in combined_logs
    assert "internal_reason=CODE_MISMATCH" in combined_logs
    assert "internal_reason=CHALLENGE_EXPIRED" in combined_logs
    assert "111222" not in combined_logs
    assert "u1@qq.com" not in combined_logs
    assert metrics.snapshot()
