def _seed_user(schema: str, uid: int, *, email: str | None = None, phone: str | None = None) -> None:
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO app_user (id, user_no, status, session_version) VALUES (%s, %s, 'active', 1)", (uid, f"U{uid}")
        )
        cur.execute(
            "INSERT INTO user_credential (user_id, username, phone, password_hash, password_configured, status) "
            "VALUES (%s, %s, %s, %s, true, 'active')",
            (uid, f"revu_{uid}", phone, hash_password("InitPass!2026")),
        )
        cur.execute("INSERT INTO user_profile (user_id, display_name) VALUES (%s, %s)", (uid, f"User{uid}"))
        cur.execute("INSERT INTO user_role (user_id, role_code) VALUES (%s, 'user')", (uid,))
        if email:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'email', %s, NOW(), 'active', 'email')",
                (uid, email),
            )
        if phone:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'phone', %s, NOW(), 'active', 'sms')",
                (uid, phone),
            )


def _insert_recovery_challenge(schema: str, uid: int, contact: str, code: str, *, channel: str = "email_otp") -> str:
    cid = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO auth_challenge(id, user_id, purpose, channel, destination_fingerprint, destination_masked, "
            "code_hash, status, send_state, expires_at, code_hash_version) "
            "VALUES (%s, %s, 'password_recovery', %s, %s, 'm***', %s, 'pending', 'accepted', NOW() + INTERVAL '5 minutes', 2)",
            (cid, uid, channel, _fingerprint(contact), _hmac_code_v2(cid, "password_recovery", channel, contact, code)),
        )
    return cid


def _ctx(tok: str, uid: int):
    return session_context_from_request(SimpleNamespace(headers={"Authorization": f"Bearer {tok}"}), uid)


def test_change_password_and_recovery_complete_revoke_all_credentials_and_invalidate_post_commit(rev_env):
    """覆盖 RF04/A12/RF-A12/RF-A13：改密与密码重置撤销全部历史挑战、Recovery/Step-up Grant 与会话，且严格在 commit 后清理缓存。"""
    schema, _em = rev_env
    _seed_user(schema, 6001, email="u6001@qq.com", phone="13800136001")
    sess = password_login_session("revu_6001", "InitPass!2026")
    sctx = _ctx(sess["accessToken"], 6001)

    # 制造：历史 pending/verified recovery challenge + active recovery_grant + step_up_auth challenge + active step_up_grant
    cid_rec_verified = _insert_recovery_challenge(schema, 6001, "u6001@qq.com", "111222", channel="email_otp")
    rg_old = verify_recovery_challenge(cid_rec_verified, "111222")["recoveryGrant"]
    cid_rec_pending = _insert_recovery_challenge(schema, 6001, "13800136001", "333444", channel="sms")
    su_old = issue_step_up_grant(
        6001,
        purpose="rebind_email",
        method="password",
        session_fingerprint=sctx.fingerprint_for_purpose("rebind_email"),
        session_ctx=sctx,
        current_password="InitPass!2026",
        target_contact="new6001@qq.com",
    )["stepUpGrant"]
    cid_su = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            """
            INSERT INTO auth_challenge(
                id, user_id, purpose, channel, destination_fingerprint, destination_masked,
                code_hash, status, send_state, expires_at, code_hash_version,
                session_id, session_version, sub_purpose, target_fingerprint, source_contact_fingerprint
            ) VALUES (
                %s, 6001, 'step_up_auth', 'email_otp', %s, 'u***',
                %s, 'pending', 'accepted', NOW() + INTERVAL '5 minutes', 2,
                %s, 1, 'rebind_email', %s, %s
            )
            """,
            (
                cid_su,
                _fingerprint("u6001@qq.com"),
                _hmac_code_v2(cid_su, "step_up_auth", "email_otp", "u6001@qq.com", "555666"),
                sctx.sid,
                _target_fingerprint("new6001@qq.com", purpose="rebind_email"),
                _fingerprint("u6001@qq.com"),
            ),
        )

    events: list[str] = []
    from modules.identity import service as id_svc

    orig_gc = id_svc.get_cursor

    @contextmanager
    def _observed_gc(commit: bool = False):
        events.append(f"enter(commit={commit})")
        with orig_gc(commit=commit) as c:
            yield c
        if commit:
            events.append("committed")

    orig_invalidate = auth_cache.invalidate_user

    def _obs_invalidate(uid: int) -> None:
        events.append(f"invalidate({uid})")
        orig_invalidate(uid)

    # 1. 普通改密 -> 撤销上述全部历史凭证，且 invalidate_user 在 committed 之后触发
    with (
        patch("modules.identity.service.get_cursor", _observed_gc),
        patch("modules.identity.service.auth_cache.invalidate_user", side_effect=_obs_invalidate),
    ):
        change_password(6001, "InitPass!2026", "NewPass!6001A")

    assert "committed" in events and "invalidate(6001)" in events
    assert events.index("committed") < events.index("invalidate(6001)")

    with _schema_cursor(PG_DSN, schema, commit=False) as cur:
        cur.execute("SELECT session_version FROM app_user WHERE id=6001")
        assert cur.fetchone()["session_version"] == 2
        cur.execute("SELECT COUNT(*) AS cnt FROM auth_session WHERE user_id=6001 AND status='active'")
        assert cur.fetchone()["cnt"] == 0
        cur.execute("SELECT COUNT(*) AS cnt FROM recovery_grant WHERE user_id=6001 AND status='active'")
        assert cur.fetchone()["cnt"] == 0
        cur.execute("SELECT COUNT(*) AS cnt FROM step_up_grant WHERE user_id=6001 AND status='active'")
        assert cur.fetchone()["cnt"] == 0
        cur.execute(
            "SELECT status FROM auth_challenge WHERE id IN (%s, %s, %s)",
            (cid_rec_verified, cid_rec_pending, cid_su),
        )
        statuses = {r["status"] for r in cur.fetchall()}
        assert statuses == {"cancelled"}

    # 旧 recoveryGrant、旧 refreshToken、旧 stepUpGrant 均不得再使用
    with pytest.raises(BizError):
        complete_password_recovery(rg_old, "ShouldFail!1")
    with pytest.raises(BizError):
        refresh_session(sess["refreshToken"])
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        with pytest.raises(BizError):
            validate_step_up_grant(
                cur,
                user_id=6001,
                grant_token=su_old,
                purpose="rebind_email",
                session_fingerprint=sctx.fingerprint_for_purpose("rebind_email"),
                session_ctx=sctx,
                target_contact="new6001@qq.com",
            )

    # 2. 密码找回重置（complete_password_recovery）与事务回滚对比验证
    sess2 = password_login_session("revu_6001", "NewPass!6001A")
    sctx2 = _ctx(sess2["accessToken"], 6001)
    cid_a = _insert_recovery_challenge(schema, 6001, "u6001@qq.com", "101010", channel="email_otp")
    cid_b = _insert_recovery_challenge(schema, 6001, "13800136001", "202020", channel="sms")
    rg_a = verify_recovery_challenge(cid_a, "101010")["recoveryGrant"]
    # 签发新 Grant rg_b 时会自动撤销历史 Grant rg_a
    rg_b = verify_recovery_challenge(cid_b, "202020")["recoveryGrant"]
    cid_c = _insert_recovery_challenge(schema, 6001, "u6001@qq.com", "303030", channel="email_link")
    su_c = issue_step_up_grant(
        6001,
        purpose="rebind_email",
        method="password",
        session_fingerprint=sctx2.fingerprint_for_purpose("rebind_email"),
        session_ctx=sctx2,
        current_password="NewPass!6001A",
        target_contact="rebind6001c@qq.com",
    )["stepUpGrant"]

    rec_events: list[str] = []
    with (
        patch("core.auth_cache.invalidate_user", side_effect=lambda u: rec_events.append(f"inv:{u}")),
        patch("modules.security.service.audit_record", side_effect=RuntimeError("simulated commit failure")),
    ):
        with pytest.raises(RuntimeError):
            complete_password_recovery(rg_b, "NewPass!6001B")
    # 事务回滚时不得调用 invalidate_user
    assert rec_events == []

    # 正常完成 B 重置 -> A 已提前被撤销，C、su_c 及会话全部在同一事务收敛失效
    complete_password_recovery(rg_b, "NewPass!6001C")
    with _schema_cursor(PG_DSN, schema, commit=False) as cur:
        cur.execute("SELECT session_version FROM app_user WHERE id=6001")
        assert cur.fetchone()["session_version"] == 3
        cur.execute("SELECT COUNT(*) AS cnt FROM recovery_grant WHERE user_id=6001 AND status='active'")
        assert cur.fetchone()["cnt"] == 0
        cur.execute("SELECT COUNT(*) AS cnt FROM step_up_grant WHERE user_id=6001 AND status='active'")
        assert cur.fetchone()["cnt"] == 0
        cur.execute(
            "SELECT COUNT(*) AS cnt FROM auth_challenge WHERE user_id=6001 AND status IN ('pending_send','pending','verified')"
        )
        assert cur.fetchone()["cnt"] == 0
        cur.execute("SELECT status FROM auth_challenge WHERE id=%s", (cid_c,))
        assert cur.fetchone()["status"] == "cancelled"
    with pytest.raises(BizError):
        complete_password_recovery(rg_a, "ShouldFail!2")
    with pytest.raises(BizError):
        complete_password_recovery(rg_b, "ShouldFailReplay!2")
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        with pytest.raises(BizError):
            validate_step_up_grant(
                cur,
                user_id=6001,
                grant_token=su_c,
                purpose="rebind_email",
                session_fingerprint=sctx2.fingerprint_for_purpose("rebind_email"),
                session_ctx=sctx2,
                target_contact="rebind6001c@qq.com",
            )
    with pytest.raises(BizError):
        refresh_session(sess2["refreshToken"])


def test_rebind_contact_and_user_disable_revoke_old_credentials(rev_env):
    """覆盖：联系方式换绑（含手机换绑）清理历史恢复凭据，管理员禁用账号立即阻断全部认证与恢复凭证。"""
    schema, _em = rev_env
    _seed_user(schema, 6002, email="u6002@qq.com", phone="13800136002")
    sess = password_login_session("revu_6002", "InitPass!2026")
    sctx = _ctx(sess["accessToken"], 6002)

    # 先产生一条基于旧手机的恢复 Grant 与待绑定手机 Challenge
    cid_rec_sms = _insert_recovery_challenge(schema, 6002, "13800136002", "445566", channel="sms")
    rg_sms = verify_recovery_challenge(cid_rec_sms, "445566")["recoveryGrant"]

    su_phone = issue_step_up_grant(
        6002,
        purpose="rebind_phone",
        method="password",
        session_fingerprint=sctx.fingerprint_for_purpose("rebind_phone"),
        session_ctx=sctx,
        current_password="InitPass!2026",
        target_contact="13900136999",
    )["stepUpGrant"]
    cid_bind_phone = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO auth_challenge(id, user_id, purpose, channel, destination_fingerprint, destination_masked, "
            "code_hash, status, send_state, expires_at, code_hash_version) "
            "VALUES (%s, 6002, 'bind_phone', 'sms', %s, '139***', %s, 'pending', 'accepted', NOW() + INTERVAL '5 minutes', 2)",
            (
                cid_bind_phone,
                _fingerprint("13900136999"),
                _hmac_code_v2(cid_bind_phone, "bind_phone", "sms", "13900136999", "667788"),
            ),
        )
    verify_and_bind_contact(6002, cid_bind_phone, "667788", "13900136999", step_up_grant=su_phone, session_ctx=sctx)
    with _schema_cursor(PG_DSN, schema, commit=False) as cur:
        cur.execute("SELECT status FROM recovery_grant WHERE user_id=6002")
        assert [r["status"] for r in cur.fetchall()] == ["revoked"]
    with pytest.raises(BizError):
        complete_password_recovery(rg_sms, "OldSmsGrant!1")

    # 账号被禁用后（status='disabled'）：访问令牌、refresh、step-up、恢复均立即 Fail-Closed
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute("UPDATE app_user SET status='disabled' WHERE id=6002")
    with pytest.raises(BizError) as exc_id:
        identity(SimpleNamespace(headers={"Authorization": f"Bearer {sess['accessToken']}"}))
    assert exc_id.value.http_status == 401
    with pytest.raises(BizError):
        refresh_session(sess["refreshToken"])
    cid_after_dis = _insert_recovery_challenge(schema, 6002, "u6002@qq.com", "998877", channel="email_otp")
    with pytest.raises(BizError):
        verify_recovery_challenge(cid_after_dis, "998877")
