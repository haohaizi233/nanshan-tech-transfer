def test_delivery_fault_injection_and_redis_coordination():
    """覆盖 RF06 / RF10 / RF12 / RF-A21 / RF-A29 / RF-A30：数据库写/提交/风控回调/Provider未知异常全故障注入矩阵。"""
    if not PG_DSN:
        pytest.skip("SMS_TEST_POSTGRES / SMS_TEST_POSTGRES_DSN not configured")
    schema = f"fi_rf_{uuid.uuid4().hex[:10]}"
    conn = psycopg2.connect(PG_DSN)
    conn.autocommit = True

    class _FaultEmailProvider(MockEmailProvider):
        provider_name = "mock"
        provider_config_id = "mock:fi"

        def __init__(self, exc_to_raise: Exception | None = None) -> None:
            super().__init__()
            self.exc_to_raise = exc_to_raise
            self.calls = 0

        def send_code_task(
            self, email: str, code: str, purpose: str, ttl_seconds: int, *, send_request_id: str | None = None
        ):
            self.calls += 1
            if self.exc_to_raise is not None:
                raise self.exc_to_raise
            return super().send_code_task(email, code, purpose, ttl_seconds, send_request_id=send_request_id)

    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            _apply_sql(cur, schema, _BASE_TABLES_SQL)
            for mig in (
                "033_unified_account_security.sql",
                "034_sms_security_gateway.sql",
                "035_sms_delivery_diagnostics.sql",
                "036_email_security_gateway.sql",
                "037_phase_r_security_hardening.sql",
                "038_phase_r_final_security.sql",
                "039_phase_r_hotfix.sql",
            ):
                _apply_sql(cur, schema, (MIGRATION_DIR / mig).read_text(encoding="utf-8"))
            cur.execute(
                "INSERT INTO app_user(id, user_no, status, session_version) VALUES (9001, 'U9001', 'active', 1)"
            )
            cur.execute(
                "INSERT INTO user_credential(user_id, username, password_hash, password_configured, status) "
                "VALUES (9001, 'fi_9001', %s, true, 'active')",
                (hash_password("InitPass!2026"),),
            )

        def _factory(commit: bool = False):
            return _schema_cursor(PG_DSN, schema, commit=commit)

        # 1) RF10 (RF-A29): transition_risk_checked 当 engine.transition 返回 False 或抛异常时，记录诊断指标并安全返回不掩盖真实发送状态
        class _FalseEngine:
            def transition(self, *args, **kwargs):
                return False

        class _BoomEngine:
            def transition(self, *args, **kwargs):
                raise ConnectionError("redis connection dropped")

        metrics.reset() if hasattr(metrics, "reset") else None
        assert (
            transition_risk_checked(
                _FalseEngine(), "cid-f1", "accepted", channel="email_otp", purpose="password_recovery"
            )
            is False
        )
        assert (
            transition_risk_checked(
                _BoomEngine(), "cid-f2", "accepted", channel="email_otp", purpose="password_recovery"
            )
            is False
        )

        # 2) 创建挑战期间数据库异常 -> 释放 Redis 占用的 slot，且 Provider 调用 0 次
        transitions: list[str] = []
        eng_rec = SimpleNamespace(
            reserve=lambda *a, **k: RiskDecision(DecisionAction.ALLOW),
            transition=lambda _cid, target: transitions.append(target) or True,
        )
        em_never = _FaultEmailProvider()
        reset_providers_for_test(email=em_never)
        with (
            patch.object(settings, "EMAIL_ENABLED", True),
            patch("modules.security.email_gateway.get_cursor", side_effect=psycopg2.OperationalError("write failed")),
        ):
            with pytest.raises(DeliveryStageError) as exc_ch:
                _send_email(
                    9001,
                    "fi9001@qq.com",
                    "password_recovery",
                    "email_otp",
                    str(uuid.uuid4()),
                    SendContext("192.0.2.91", "d91", "r91"),
                    engine=eng_rec,
                )
            assert exc_ch.value.stage == "challenge_create"
        assert em_never.calls == 0
        assert transitions == ["rejected"]

        # 3) Provider 超时 (outcome_unknown=True) -> auth_challenge 进入 unknown 但保持可核验 pending，不误删除
        em_timeout = _FaultEmailProvider(
            ProviderError("smtp read timeout", outcome_unknown=True, reason_code="SMTP_TIMEOUT")
        )
        reset_providers_for_test(email=em_timeout)
        cid_unk = str(uuid.uuid4())
        transitions.clear()
        with (
            ExitStack() as stack,
        ):
            stack.enter_context(patch.object(settings, "EMAIL_ENABLED", True))
            stack.enter_context(patch("modules.security.email_gateway.get_cursor", _factory))
            stack.enter_context(patch("modules.audit.service.get_cursor", _factory))
            with pytest.raises(DeliveryStageError) as exc_unk:
                _send_email(
                    9001,
                    "fi9001@qq.com",
                    "password_recovery",
                    "email_otp",
                    cid_unk,
                    SendContext("192.0.2.91", "d91", "r92"),
                    engine=eng_rec,
                )
            assert exc_unk.value.outcome_unknown is True
        assert em_timeout.calls == 1
        assert transitions == ["unknown"]
        with _schema_cursor(PG_DSN, schema, commit=False) as cur:
            cur.execute("SELECT status, send_state FROM auth_challenge WHERE id=%s", (cid_unk,))
            row = cur.fetchone()
            assert row["send_state"] == "unknown"
            assert row["status"] == "pending"

        # 4) Provider 明确拒绝 (outcome_unknown=False) -> status='failed', send_state='rejected', transitions=['rejected']
        em_rej = _FaultEmailProvider(
            ProviderError("invalid rcpt", outcome_unknown=False, reason_code="SMTP_PERMANENT_FAILURE")
        )
        reset_providers_for_test(email=em_rej)
        cid_rej = str(uuid.uuid4())
        transitions.clear()
        with ExitStack() as stack:
            stack.enter_context(patch.object(settings, "EMAIL_ENABLED", True))
            stack.enter_context(patch("modules.security.email_gateway.get_cursor", _factory))
            stack.enter_context(patch("modules.audit.service.get_cursor", _factory))
            with pytest.raises(DeliveryStageError) as exc_rej:
                _send_email(
                    9001,
                    "fi9001@qq.com",
                    "password_recovery",
                    "email_otp",
                    cid_rej,
                    SendContext("192.0.2.91", "d91", "r93"),
                    engine=eng_rec,
                )
            assert exc_rej.value.outcome_unknown is False
        assert em_rej.calls == 1
        assert transitions == ["rejected"]
        with _schema_cursor(PG_DSN, schema, commit=False) as cur:
            cur.execute("SELECT status, send_state FROM auth_challenge WHERE id=%s", (cid_rej,))
            row_r = cur.fetchone()
            assert row_r["send_state"] == "rejected"
            assert row_r["status"] == "failed"
    finally:
        reset_providers_for_test(None, None)
        with conn.cursor() as cur:
            cur.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(schema)))
        conn.close()


