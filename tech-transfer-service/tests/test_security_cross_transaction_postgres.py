    assert c08["deadlocks"] == 0 and c08["unexpected_errors"] == []
    with _schema_cursor(PG_DSN, schema, commit=False) as cur:
        cur.execute("SELECT COUNT(*) AS cnt FROM recovery_grant WHERE user_id = 40 AND status = 'active'")
        assert cur.fetchone()["cnt"] <= 1
