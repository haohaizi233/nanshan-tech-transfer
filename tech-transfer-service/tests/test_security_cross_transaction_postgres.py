def _apply_sql(cur, schema: str, raw_sql: str) -> None:
    cur.execute(raw_sql.replace("public.", f"{schema}."))


@contextmanager
def _schema_cursor(dsn: str, schema: str, commit: bool = False):
    conn = psycopg2.connect(dsn, cursor_factory=RealDictCursor)
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            yield cur
        if commit:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _sess_ctx(uid: int):
    from fastapi import Request

    from modules.security.step_up import get_cursor

    sid: str | None = None
    with get_cursor(commit=True) as cur:
        cur.execute(
            "SELECT sid FROM auth_session WHERE user_id = %s AND status = 'active' AND sid IS NOT NULL ORDER BY id LIMIT 1",
            (uid,),
        )
        row = cur.fetchone()
        if row and row.get("sid"):
            sid = str(row["sid"])
        else:
            sid = str(uuid.uuid4())
            cur.execute(
                "INSERT INTO auth_session (user_id, refresh_jti, status, sid, auth_time) "
                "VALUES (%s, %s, 'active', %s, NOW())",
                (uid, uuid.uuid4().hex, sid),
            )
    tok = sign_access_token(uid, f"U{uid}", ["user"], 1, sid=sid, auth_time=9_999_999_999)
    req = Request({"type": "http", "headers": [(b"authorization", f"Bearer {tok}".encode("latin-1"))]})
    return session_context_from_request(req, uid)


def _seed_user(schema: str, uid: int, email: str | None = None, phone: str | None = None) -> None:
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute("INSERT INTO app_user (id, user_no, status) VALUES (%s, %s, 'active')", (uid, f"U{uid}"))
        cur.execute(
            "INSERT INTO user_credential (user_id, username, phone, password_hash, password_configured, status) "
            "VALUES (%s, %s, %s, %s, true, 'active')",
            (uid, f"u{uid}", phone, hash_password("InitPass!123")),
        )
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, sid, auth_time) "
            "VALUES (%s, %s, 'active', %s, NOW())",
            (uid, uuid.uuid4().hex, str(uuid.uuid4())),
        )
        if email:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'email', %s, NOW(), 'active', 'email')",
                (uid, email),
            )
        if phone:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'phone', %s, NOW(), 'active', 'sms')",
                (uid, phone),
            )


