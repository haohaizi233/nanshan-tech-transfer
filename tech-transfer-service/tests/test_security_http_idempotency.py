def test_32_thread_idempotency_replay_conflict_scope_release_expiry_and_legacy_client(pg_redis):
    schema, em, _engine, _rc, _pref = pg_redis
    _seed(schema, 1, "u1@qq.com")

    # 1. 32 并发相同 Idempotency-Key + 相同参数 -> 仅创建 1 条入队任务、发送 1 封邮件、返回相同 challengeId
    ikey = f"rec-{uuid.uuid4()}"
    results = []
    lock = threading.Lock()
    barrier = threading.Barrier(32)

    def _worker():
        barrier.wait(timeout=10)
        resp = client.post(
            "/api/tech-transfer/v1/auth/recovery/start",
            headers={"Idempotency-Key": ikey},
            json={"account": "u1@qq.com", "channel": "email_otp"},
        )
        with lock:
            results.append((resp.status_code, resp.json()["data"]["challengeId"]))

    threads = [threading.Thread(target=_worker) for _ in range(32)]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=15)

    assert len(results) == 32
    assert all(code == 200 for code, _ in results)
    challenge_ids = {cid for _, cid in results}
    assert len(challenge_ids) == 1
    assert len(em.sent_emails) == 1
    with _schema_cursor(PG_DSN, schema, commit=False) as cur:
        cur.execute("SELECT COUNT(*) AS cnt FROM security_delivery_request WHERE idempotency_key = %s", (ikey,))
        assert cur.fetchone()["cnt"] == 1

    # 2. 同 Idempotency-Key 但参数不同 -> 409 TT_COMMON_40901
    r_conflict = client.post(
        "/api/tech-transfer/v1/auth/recovery/start",
        headers={"Idempotency-Key": ikey},
        json={"account": "other@qq.com", "channel": "email_otp"},
    )
    assert r_conflict.status_code == 409
    assert r_conflict.json()["code"] == "TT_COMMON_40901"

    # 3. 过期后允许同名 Idempotency-Key 安全轮转
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "UPDATE security_delivery_request SET idempotency_expires_at = NOW() - INTERVAL '5 seconds' "
            "WHERE idempotency_key = %s",
            (ikey,),
        )
    r_rotated = client.post(
        "/api/tech-transfer/v1/auth/recovery/start",
        headers={"Idempotency-Key": ikey},
        json={"account": "missing-u@qq.com", "channel": "email_otp"},
    )
    assert r_rotated.status_code == 200
    assert r_rotated.json()["data"]["challengeId"] not in challenge_ids

    # 4. 无 Idempotency-Key 的旧客户端仍保持完全兼容
    r_legacy = client.post(
        "/api/tech-transfer/v1/auth/recovery/start",
        json={"account": "legacy@qq.com", "channel": "email_otp"},
    )
    assert r_legacy.status_code == 200


def test_authenticated_idempotency_pre_provider_release_scope_isolation_and_unknown_outcome(pg_redis):
    schema, em, _engine, _rc, _pref = pg_redis
    _seed(schema, 11, None)
    _seed(schema, 12, None)

    sess11 = password_login_session("u11", "InitPass!123")
    sess12 = password_login_session("u12", "InitPass!123")
    tok11, tok12 = sess11["accessToken"], sess12["accessToken"]
    from fastapi import Request

    ctx11 = session_context_from_request(
        Request({"type": "http", "headers": [(b"authorization", f"Bearer {tok11}".encode("latin-1"))]}), 11
    )
    ctx12 = session_context_from_request(
        Request({"type": "http", "headers": [(b"authorization", f"Bearer {tok12}".encode("latin-1"))]}), 12
    )

    shared_key = f"bind-{uuid.uuid4()}"
    # 1. Pre-provider failure（缺少 stepUpGrant -> 403）释放幂等键，携有效 Grant 用同一 key 重试应成功
    r_pre_fail = client.post(
        "/api/tech-transfer/v1/me/security/contact/challenge",
        headers={"Authorization": f"Bearer {tok11}", "Idempotency-Key": shared_key},
        json={"contactType": "email", "contactValue": "u11target@qq.com"},
    )
    assert r_pre_fail.status_code == 403

    su11 = issue_step_up_grant(
        11,
        purpose="bind_email",
        method="password",
        session_fingerprint=ctx11.fingerprint_for_purpose("bind_email"),
        session_ctx=ctx11,
        current_password="InitPass!123",
        target_contact="u11target@qq.com",
    )["stepUpGrant"]
    r_ok11 = client.post(
        "/api/tech-transfer/v1/me/security/contact/challenge",
        headers={"Authorization": f"Bearer {tok11}", "Idempotency-Key": shared_key},
        json={"contactType": "email", "contactValue": "u11target@qq.com", "stepUpGrant": su11},
    )
    assert r_ok11.status_code == 200
    cid11 = r_ok11.json()["data"]["challengeId"]

    # 2. 不同用户复用完全相同的 Idempotency-Key 字符串隔离互不干扰
    su12 = issue_step_up_grant(
        12,
        purpose="bind_email",
        method="password",
        session_fingerprint=ctx12.fingerprint_for_purpose("bind_email"),
        session_ctx=ctx12,
        current_password="InitPass!123",
        target_contact="u12target@qq.com",
    )["stepUpGrant"]
    r_ok12 = client.post(
        "/api/tech-transfer/v1/me/security/contact/challenge",
        headers={"Authorization": f"Bearer {tok12}", "Idempotency-Key": shared_key},
        json={"contactType": "email", "contactValue": "u12target@qq.com", "stepUpGrant": su12},
    )
    assert r_ok12.status_code == 200
    assert r_ok12.json()["data"]["challengeId"] != cid11

    # 3. 同一 key 命中 DATA 后 unknown outcome 时记录 unknown，重放返回 503 且绝不重发
    su11_unk = issue_step_up_grant(
        11,
        purpose="bind_email",
        method="password",
        session_fingerprint=ctx11.fingerprint_for_purpose("bind_email"),
        session_ctx=ctx11,
        current_password="InitPass!123",
        target_contact="u11other@qq.com",
    )["stepUpGrant"]
    em.failure_error = ProviderError(
        "timeout after DATA",
        reason_code="PROVIDER_OUTCOME_UNKNOWN",
        outcome_unknown=True,
        request_attempted=True,
    )
    unk_key = f"unk-{uuid.uuid4()}"
    r_unk1 = client.post(
        "/api/tech-transfer/v1/me/security/contact/challenge",
        headers={"Authorization": f"Bearer {tok11}", "Idempotency-Key": unk_key},
        json={"contactType": "email", "contactValue": "u11other@qq.com", "stepUpGrant": su11_unk},
    )
    assert r_unk1.status_code == 503
    sent_before = len(em.sent_emails)
    em.failure_error = None
    r_unk2 = client.post(
        "/api/tech-transfer/v1/me/security/contact/challenge",
        headers={"Authorization": f"Bearer {tok11}", "Idempotency-Key": unk_key},
        json={"contactType": "email", "contactValue": "u11other@qq.com", "stepUpGrant": su11_unk},
    )
    assert r_unk2.status_code == 503
    assert len(em.sent_emails) == sent_before
