def _apply_sql(cur, schema: str, raw_sql: str) -> None:
    cur.execute(raw_sql.replace("public.", f"{schema}."))


@contextmanager
def _schema_cursor(dsn: str, schema: str, commit: bool = False):
    conn = psycopg2.connect(dsn, cursor_factory=RealDictCursor)
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            yield cur
        if commit:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _patch_all_get_cursor(stack: ExitStack, dsn: str, schema: str) -> None:
    def _factory(commit: bool = False):
        return _schema_cursor(dsn, schema, commit=commit)

    for target in (
        "db.get_cursor",
        "modules.audit.service.get_cursor",
        "modules.security.service.get_cursor",
        "modules.security.email_gateway.get_cursor",
        "modules.security.sms_gateway.get_cursor",
        "modules.security.step_up.get_cursor",
        "modules.security.email_diagnostics.get_cursor",
        "modules.security.eligibility.get_cursor",
        "modules.security.idempotency.get_cursor",
        "modules.identity.service.get_cursor",
    ):
        stack.enter_context(patch(target, _factory))


