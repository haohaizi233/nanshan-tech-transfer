def _seed_user(schema: str, user_id: int, username: str, email: str | None = None, *, verified: bool = True) -> None:
    pwd = hash_password("InitPass!123")
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute("INSERT INTO app_user(id, user_no, status) VALUES (%s, %s, 'active')", (user_id, f"U{user_id:04d}"))
        cur.execute(
            "INSERT INTO user_credential(user_id, username, password_hash, password_configured, status) VALUES (%s, %s, %s, true, 'active')",
            (user_id, username, pwd),
        )
        if email:
            cur.execute(
                """INSERT INTO account_contact(user_id, contact_type, normalized_value, verified_at, status, verification_method)
                VALUES (%s, 'email', %s, CASE WHEN %s THEN NOW() ELSE NULL END, 'active', 'email')""",
                (user_id, email, verified),
            )


