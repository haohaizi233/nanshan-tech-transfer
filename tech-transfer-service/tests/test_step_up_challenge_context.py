def _seed(schema: str, uid: int, *, email: str | None = None, phone: str | None = None) -> None:
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO app_user (id, user_no, status, session_version) VALUES (%s, %s, 'active', 1)", (uid, f"U{uid}")
        )
        cur.execute(
            "INSERT INTO user_credential (user_id, username, phone, password_hash, password_configured, status) "
            "VALUES (%s, %s, %s, %s, true, 'active')",
            (uid, f"su_{uid}", phone, hash_password("InitPass!2026")),
        )
        cur.execute("INSERT INTO user_profile (user_id, display_name) VALUES (%s, %s)", (uid, f"SU{uid}"))
        cur.execute("INSERT INTO user_role (user_id, role_code) VALUES (%s, 'user')", (uid,))
        if email:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'email', %s, NOW(), 'active', 'email')",
                (uid, email),
            )
        if phone:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'phone', %s, NOW(), 'active', 'sms')",
                (uid, phone),
            )


def _ctx(tok: str, uid: int):
    return session_context_from_request(SimpleNamespace(headers={"Authorization": f"Bearer {tok}"}), uid)


def test_su01_to_su12_step_up_challenge_full_context_binding_and_rejects(su_env):
    """覆盖 SU01-SU12：Step-up Challenge 上下文全绑定、DB CHECK 拒绝不完整行、跨用户/会话/版本/用途/目标/渠道拒绝。"""
    schema, em, _sms = su_env
    _seed(schema, 7001, email="old7001@qq.com", phone="13800137001")
    _seed(schema, 7002, email="old7002@qq.com", phone="13800137002")

    s71_a = password_login_session("su_7001", "InitPass!2026")
    s71_b = password_login_session("su_7001", "InitPass!2026")
    s72 = password_login_session("su_7002", "InitPass!2026")
    ctx71_a = _ctx(s71_a["accessToken"], 7001)
    ctx71_b = _ctx(s71_b["accessToken"], 7001)
    ctx72 = _ctx(s72["accessToken"], 7002)

    # SU02: DB CHECK 约束 chk_auth_challenge_stepup_context 拒绝缺失 session_id / sub_purpose / target_fingerprint
    with pytest.raises(psycopg2.errors.CheckViolation):
        with _schema_cursor(PG_DSN, schema, commit=True) as cur:
            cur.execute(
                "INSERT INTO auth_challenge(id, user_id, purpose, channel, destination_fingerprint, destination_masked, "
                "code_hash, status, send_state, expires_at, code_hash_version) "
                "VALUES (%s, 7001, 'step_up_auth', 'email_otp', %s, 'o***', %s, 'pending', 'accepted', NOW() + INTERVAL '5 minutes', 2)",
                (str(uuid.uuid4()), uuid.uuid4().hex, uuid.uuid4().hex),
            )

    # SU01: 正常签发 step_up_auth challenge 并持久化全部 5 个安全上下文字段
    res_ch = start_step_up_challenge(
        7001,
        purpose="rebind_email",
        method="old_email_otp",
        context=SendContext("192.0.2.71", "d71", "r71"),
        target_contact="target7001@qq.com",
        session_ctx=ctx71_a,
    )
    cid = res_ch["challengeId"]
    otp = em.get_last_code("old7001@qq.com")
    assert otp
    with _schema_cursor(PG_DSN, schema, commit=False) as cur:
        cur.execute(
            "SELECT session_id, session_version, sub_purpose, target_fingerprint, source_contact_fingerprint "
            "FROM auth_challenge WHERE id=%s",
            (cid,),
        )
        row = cur.fetchone()
    assert str(row["session_id"]) == ctx71_a.sid
    assert row["session_version"] == 1
    assert row["sub_purpose"] == "rebind_email"
    assert row["target_fingerprint"] == _target_fingerprint("target7001@qq.com", purpose="rebind_email")
    assert row["source_contact_fingerprint"] == _fingerprint("old7001@qq.com")

    # SU03: 跨用户尝试用 7002 消费 7001 的 Step-up Challenge -> 拒绝
    with pytest.raises(BizError):
        issue_step_up_grant(
            7002,
            purpose="rebind_email",
            method="old_email_otp",
            session_fingerprint=ctx72.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx72,
            challenge_id=cid,
            code=otp,
            target_contact="target7001@qq.com",
        )

    # SU04: 同用户不同会话 ctx71_b 跨会话核验 -> 拒绝
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="rebind_email",
            method="old_email_otp",
            session_fingerprint=ctx71_b.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx71_b,
            challenge_id=cid,
            code=otp,
            target_contact="target7001@qq.com",
        )

    # SU05: 跨用途 (sub_purpose='rebind_email', 企图按 'bind_email' 核验) -> 拒绝
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="bind_email",
            method="old_email_otp",
            session_fingerprint=ctx71_a.fingerprint_for_purpose("bind_email"),
            session_ctx=ctx71_a,
            challenge_id=cid,
            code=otp,
            target_contact="target7001@qq.com",
        )

    # SU06: 跨目标地址 -> 拒绝
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="rebind_email",
            method="old_email_otp",
            session_fingerprint=ctx71_a.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx71_a,
            challenge_id=cid,
            code=otp,
            target_contact="hijacked@qq.com",
        )

    # SU07: 渠道不匹配（email_otp challenge 企图用 old_phone_otp 方式核验）-> 拒绝
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="rebind_email",
            method="old_phone_otp",
            session_fingerprint=ctx71_a.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx71_a,
            challenge_id=cid,
            code=otp,
            target_contact="target7001@qq.com",
        )

    # SU08: session_version 变更导致 challenge 会话版本不一致 -> 拒绝
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute("UPDATE app_user SET session_version=2 WHERE id=7001")
    tok_v2 = sign_access_token(7001, "U7001", ["user"], 2, sid=ctx71_a.sid, auth_time=int(time.time()))
    ctx71_v2 = _ctx(tok_v2, 7001)
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="rebind_email",
            method="old_email_otp",
            session_fingerprint=ctx71_v2.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx71_v2,
            challenge_id=cid,
            code=otp,
            target_contact="target7001@qq.com",
        )
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute("UPDATE app_user SET session_version=1 WHERE id=7001")

    # SU09-SU12: 错误 OTP、未投递成功 send_state='rejected'、以及缺少上下文的历史不完整行均不可换取 Grant
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="rebind_email",
            method="old_email_otp",
            session_fingerprint=ctx71_a.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx71_a,
            challenge_id=cid,
            code="000000",
            target_contact="target7001@qq.com",
        )
    # 核验正确上下文成功拿取一次 Grant，再二次重放同 Challenge 必须失败（不可重放）
    grant_res = issue_step_up_grant(
        7001,
        purpose="rebind_email",
        method="old_email_otp",
        session_fingerprint=ctx71_a.fingerprint_for_purpose("rebind_email"),
        session_ctx=ctx71_a,
        challenge_id=cid,
        code=otp,
        target_contact="target7001@qq.com",
    )
    assert grant_res["stepUpGrant"]
    with pytest.raises(BizError):
        issue_step_up_grant(
            7001,
            purpose="rebind_email",
            method="old_email_otp",
            session_fingerprint=ctx71_a.fingerprint_for_purpose("rebind_email"),
            session_ctx=ctx71_a,
            challenge_id=cid,
            code=otp,
            target_contact="target7001@qq.com",
        )


