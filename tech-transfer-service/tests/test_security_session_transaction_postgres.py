def _apply_sql(cur, schema: str, raw_sql: str) -> None:
    cur.execute(raw_sql.replace("public.", f"{schema}."))


@contextmanager
def _schema_cursor(dsn: str, schema: str, commit: bool = False):
    conn = psycopg2.connect(dsn, cursor_factory=RealDictCursor)
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            yield cur
        if commit:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _run_tx_case(fns) -> dict:
    """并发执行多个真实 DB 事务并通过 db retry observer 透明统计真实 40P01/40001。"""
    metrics = {
        "success_count": 0,
        "business_rejected_count": 0,
        "deadlock_count": 0,
        "handled_retries": 0,
        "serialization_failure_count": 0,
        "timeout_count": 0,
        "unexpected_error_count": 0,
        "results": [],
    }
    lock = threading.Lock()
    barrier = threading.Barrier(len(fns))

    def _observer(pgcode: str, exc: BaseException) -> None:
        with lock:
            metrics["handled_retries"] += 1
            if pgcode == "40P01":
                metrics["deadlock_count"] += 1
            elif pgcode == "40001":
                metrics["serialization_failure_count"] += 1

    def _worker(fn) -> None:
        tok = set_concurrency_retry_observer(_observer)
        try:
            barrier.wait(timeout=10)
            out = fn()
            with lock:
                metrics["success_count"] += 1
                metrics["results"].append(("ok", out))
        except BizError as exc:
            with lock:
                metrics["business_rejected_count"] += 1
                metrics["results"].append(("biz_err", exc.code))
        except psycopg2.Error as exc:
            pgcode = getattr(exc, "pgcode", None)
            msg = str(exc).lower()
            with lock:
                if pgcode == "40P01" or "deadlock" in msg:
                    metrics["deadlock_count"] += 1
                elif pgcode == "40001" or "could not serialize" in msg:
                    metrics["serialization_failure_count"] += 1
                elif "timeout" in msg:
                    metrics["timeout_count"] += 1
                else:
                    metrics["unexpected_error_count"] += 1
                metrics["results"].append(("pg_err", pgcode or msg))
        except Exception as exc:
            with lock:
                metrics["unexpected_error_count"] += 1
                metrics["results"].append(("err", repr(exc)))
        finally:
            reset_concurrency_retry_observer(tok)

    threads = [threading.Thread(target=_worker, args=(fn,)) for fn in fns]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=20)
    return metrics


