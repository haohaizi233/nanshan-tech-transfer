def test_id01_to_id08_lifecycle_finalize_failure_unknown_and_active_ttl_protection(idem_env):
    """覆盖 ID01-ID08：阶段推进、Provider成功后落盘失败不释放幂等键（RF8）、活跃及unknown TTL到期保护。"""
    schema, em, _client, _eng = idem_env
    _seed(schema, 8001, email="u8001@qq.com")

    # ID01 & ID02: 首请求声明 idem_pending -> pre_provider -> send_claimed -> provider_called -> response_persisted，同键重放命中缓存
    c1 = claim_http_idempotency(
        scope="s1",
        key="k-id01",
        request_hash="hash-1",
        channel="email_otp",
        purpose="bind_email",
        payload={"account": "u8001@qq.com"},
        initial_state="idem_pending",
    )
    assert c1.replay is False and c1.execution_stage == "pre_provider" and c1.state == "idem_pending"
    assert advance_idempotency_stage(c1, ("pre_provider",), "send_claimed") is True
    assert advance_idempotency_stage(c1, ("send_claimed",), "provider_called", provider_called=True) is True
    assert finalize_http_idempotency(c1, {"challengeId": c1.task_id, "sent": True}, state="completed") is True

    replay = claim_http_idempotency(
        scope="s1", key="k-id01", request_hash="hash-1", channel="email_otp", purpose="bind_email"
    )
    assert replay.replay is True and replay.cached_response == {"challengeId": c1.task_id, "sent": True}
    with pytest.raises(BizError) as exc_conf:
        claim_http_idempotency(
            scope="s1", key="k-id01", request_hash="hash-DIFFERENT", channel="email_otp", purpose="bind_email"
        )
    assert exc_conf.value.http_status == 409

    # ID03 & ID04 (RF8): Provider 发送已真实调用成功（execution_stage='provider_called'），之后写响应失败 -> mark_http_idempotency_unknown，
    # 幂等键绝不释放，同键重放仍返回 unknown（禁止再次发信）
    c3 = claim_http_idempotency(
        scope="s3",
        key="k-rf8-persist-fail",
        request_hash="hash-3",
        channel="email_otp",
        purpose="bind_email",
        payload={"account": "u8001@qq.com"},
    )
    _send_email(
        8001,
        "u8001@qq.com",
        "bind_email",
        "email_otp",
        str(uuid.uuid4()),
        SendContext("192.0.2.81", "d81", "r81"),
        idempotency_claim=c3,
    )
    assert em.calls == 1
    assert mark_http_idempotency_unknown(c3, "IDEMPOTENCY_FINALIZE_DB_ERROR") is True

    # 即使之后误调 release_http_idempotency_on_pre_provider_failure 也绝不清空幂等键！
    assert release_http_idempotency_on_pre_provider_failure(c3, "late_except") is False

    replay3 = claim_http_idempotency(
        scope="s3", key="k-rf8-persist-fail", request_hash="hash-3", channel="email_otp", purpose="bind_email"
    )
    assert replay3.replay is True and replay3.state == "unknown" and replay3.key == "k-rf8-persist-fail"

    # ID05 & ID06: 仅在 pre_provider 且 provider_called=false 时允许安全释放幂等键
    c5 = claim_http_idempotency(
        scope="s5", key="k-pre-fail", request_hash="hash-5", channel="email_otp", purpose="bind_email"
    )
    assert release_http_idempotency_on_pre_provider_failure(c5, "RATE_LIMIT") is True
    c5_retry = claim_http_idempotency(
        scope="s5", key="k-pre-fail", request_hash="hash-5", channel="email_otp", purpose="bind_email"
    )
    assert c5_retry.replay is False and c5_retry.task_id != c5.task_id

    # ID07 & ID08: 活跃 idem_pending 与 unknown 记录即便 idempotency_expires_at <= NOW() 也不得被 claim_http_idempotency 覆盖重发
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO security_delivery_request (id, payload, state, request_id, channel, purpose, "
            "idempotency_scope, idempotency_key, request_hash, idempotency_expires_at, execution_stage, idem_claimed_at) "
            "VALUES (%s, '{\"account\":\"a@qq.com\"}'::jsonb, 'idem_pending', 'r7', 'email_otp', 'bind_email', 's7', 'k-active-expired', 'h7', NOW() - INTERVAL '5 seconds', 'pre_provider', NOW()),"
            "       (%s, '{}'::jsonb, 'unknown', 'r8', 'email_otp', 'bind_email', 's8', 'k-unk-expired', 'h8', NOW() - INTERVAL '5 seconds', 'provider_unknown', NOW())",
            (str(uuid.uuid4()), str(uuid.uuid4())),
        )
    r_act = claim_http_idempotency(
        scope="s7", key="k-active-expired", request_hash="h7", channel="email_otp", purpose="bind_email"
    )
    assert r_act.replay is True and r_act.state == "idem_pending"
    r_unk = claim_http_idempotency(
        scope="s8", key="k-unk-expired", request_hash="h8", channel="email_otp", purpose="bind_email"
    )
    assert r_unk.replay is True and r_unk.state == "unknown"


