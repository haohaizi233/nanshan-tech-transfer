def test_s01_to_s08_execution_right_cas_and_zero_provider_calls(pg_redis):
    """覆盖 S01-S08：CAS 声明成功条件、失败/异常/过期/cancelled/owner不匹配时 Provider Spy 调用次数严格为 0，10并发竞争仅1次发信。"""
    schema, _engine = pg_redis
    _seed_user(schema, 3001, email="u3001@qq.com", phone="13800133001")

    # S01: 合法 pending_send + reserved + 未过期 声明成功
    cid_ok = _insert_challenge(schema, 3001)
    r_s01 = claim_send_execution_right(cid_ok, send_owner="w-alpha", provider_name="mock")
    assert r_s01.outcome == "transitioned"
    assert r_s01.current_send_state == "sending"

    # S07: 另一执行者持不同 expected_owner 尝试从 sending 推向 accepted -> owner_mismatch
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        r_s07 = transition_delivery_state(cur, cid_ok, ("sending",), "accepted", expected_owner="w-beta")
    assert r_s07.updated is False
    assert r_s07.outcome == "owner_mismatch"

    # S08: accepted 后再认领 reserved -> sending -> 失败
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        r_acc = transition_delivery_state(cur, cid_ok, ("sending",), "accepted", expected_owner="w-alpha")
        assert r_acc.updated is True
    r_s08 = claim_send_execution_right(cid_ok, send_owner="w-gamma")
    assert r_s08.outcome == "conflict_or_disallowed"

    # S05 & S06: cancelled / verified / expired 均无法抢占发送权（使用独立挑战用户避免触发单用户唯一激活约束）
    _seed_user(schema, 3011, email="u3011@qq.com")
    _seed_user(schema, 3012, email="u3012@qq.com")
    cid_cancel = _insert_challenge(schema, 3011, status="cancelled", send_state="reserved")
    assert claim_send_execution_right(cid_cancel, send_owner="w1").outcome == "conflict_or_disallowed"
    cid_ver = _insert_challenge(schema, 3011, status="verified", send_state="accepted")
    assert claim_send_execution_right(cid_ver, send_owner="w1").outcome == "conflict_or_disallowed"
    cid_exp = _insert_challenge(schema, 3012, status="pending_send", send_state="reserved", expired=True)
    r_exp = claim_send_execution_right(cid_exp, send_owner="w1")
    assert r_exp.outcome == "expired"
    assert r_exp.updated is False

    # S04: 10 个并发线程对同一 pending_send + reserved challenge 抢占发送权，严格只有一个赢得 Provider 调用权
    cid_race = _insert_challenge(schema, 3011)
    spy_race = SpyEmailProvider()
    winners: list[str] = []
    barrier = threading.Barrier(10)
    lock = threading.Lock()

    def _race_worker(idx: int) -> None:
        barrier.wait(timeout=5)
        res = claim_send_execution_right(cid_race, send_owner=f"worker-{idx}", provider_name="mock")
        if res.outcome == "transitioned":
            with lock:
                winners.append(f"worker-{idx}")
            spy_race.send_code_task("u3001@qq.com", "123456", "password_recovery", 300, send_request_id=cid_race)

    threads = [threading.Thread(target=_race_worker, args=(i,)) for i in range(10)]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=10)
    assert len(winners) == 1
    assert spy_race.call_count == 1

    # S02 & S03: _send_email / _send_sms 在 CAS 冲突或 DB 失败时，Provider Spy 严格 0 次调用
    spy_em = SpyEmailProvider()
    spy_sms = SpySmsProvider()
    reset_providers_for_test(email=spy_em, sms=spy_sms)
    allow_eng = SimpleNamespace(
        reserve=lambda *a, **k: RiskDecision(DecisionAction.ALLOW),
        transition=lambda *a, **k: True,
    )

    for bad_outcome in (
        DeliveryTransitionResult(
            updated=False, outcome="conflict_or_disallowed", current_send_state="sending", current_status="pending_send"
        ),
        DeliveryTransitionResult(updated=False, outcome="database_error", current_send_state=None, current_status=None),
    ):
        with patch("modules.security.email_gateway.claim_send_execution_right", return_value=bad_outcome):
            with pytest.raises(DeliveryStageError) as exc_e:
                _send_email(
                    3001,
                    "u3001@qq.com",
                    "password_recovery",
                    "email_otp",
                    str(uuid.uuid4()),
                    SendContext("192.0.2.1", "d1", "r1"),
                    engine=allow_eng,
                )
            assert exc_e.value.stage == "send_claim"
            assert exc_e.value.request_attempted is False
        with patch("modules.security.sms_gateway.claim_send_execution_right", return_value=bad_outcome):
            with pytest.raises(DeliveryStageError) as exc_s:
                _send_sms(
                    3001,
                    "13800133001",
                    "password_recovery",
                    str(uuid.uuid4()),
                    SendContext("192.0.2.1", "d1", "r1"),
                    allow_eng,
                )
            assert exc_s.value.stage == "send_claim"
            assert exc_s.value.request_attempted is False

    # 数据库抛异常同样 0 次调用
    with patch("modules.security.email_gateway.claim_send_execution_right", side_effect=RuntimeError("db down")):
        with pytest.raises(DeliveryStageError) as exc_db:
            _send_email(
                3001,
                "u3001@qq.com",
                "password_recovery",
                "email_otp",
                str(uuid.uuid4()),
                SendContext("192.0.2.1", "d1", "r1"),
                engine=allow_eng,
            )
        assert exc_db.value.reason_code == "SEND_CLAIM_DATABASE_ERROR"

    assert spy_em.call_count == 0
    assert spy_sms.call_count == 0


