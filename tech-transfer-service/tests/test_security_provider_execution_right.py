def _apply_sql(cur, schema: str, raw_sql: str) -> None:
    cur.execute(raw_sql.replace("public.", f"{schema}."))


@contextmanager
def _schema_cursor(dsn: str, schema: str, commit: bool = False):
    conn = psycopg2.connect(dsn, cursor_factory=RealDictCursor)
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            yield cur
        if commit:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


class SpyEmailProvider(MockEmailProvider):
    provider_name = "mock"
    provider_config_id = "mock:spy"

    def __init__(self, *, mode: str = "ok") -> None:
        super().__init__()
        self.mode = mode
        self.call_count = 0
        self._lock = threading.Lock()

    def send_code_task(
        self, email: str, code: str, purpose: str, ttl_seconds: int, *, send_request_id: str | None = None
    ) -> DeliveryReceipt:
        with self._lock:
            self.call_count += 1
        if self.mode == "reject":
            raise ProviderError("spy rejected", outcome_unknown=False, reason_code="provider_rejected")
        if self.mode == "unknown":
            raise ProviderError("spy timeout", outcome_unknown=True, reason_code="provider_timeout")
        return super().send_code_task(email, code, purpose, ttl_seconds, send_request_id=send_request_id)

    def send_reset_link_task(
        self, email: str, reset_url: str, ttl_seconds: int, *, send_request_id: str | None = None
    ) -> DeliveryReceipt:
        with self._lock:
            self.call_count += 1
        if self.mode == "reject":
            raise ProviderError("spy rejected", outcome_unknown=False, reason_code="provider_rejected")
        if self.mode == "unknown":
            raise ProviderError("spy timeout", outcome_unknown=True, reason_code="provider_timeout")
        return super().send_reset_link_task(email, reset_url, ttl_seconds, send_request_id=send_request_id)

    def query_status(self, message_ids: list[str], request_date: str | None = None) -> dict:
        if self.mode == "delivered":
            return {"records": [{"MessageId": message_ids[0], "DeliverStatus": 0}]}
        if self.mode == "bounced":
            return {"records": [{"MessageId": message_ids[0], "DeliverStatus": 4}]}
        return {"records": []}


class SpySmsProvider(SmsProvider):
    def __init__(self, *, mode: str = "ok") -> None:
        self._inner = MockSmsProvider()
        self.mode = mode
        self.call_count = 0
        self._lock = threading.Lock()

    def send_code(self, phone: str, code: str, ttl_seconds: int) -> dict:
        with self._lock:
            self.call_count += 1
        if self.mode == "reject":
            raise ProviderError("sms rejected", outcome_unknown=False, reason_code="sms_rejected")
        return self._inner.send_code(phone, code, ttl_seconds)

    def query_status(self, provider_ids: list[str], days: int = 2, start: int = 0, limit: int = 50) -> dict:
        return {"accepted": True, "records": [{"smsId": provider_ids[0], "status": 200}]}


