def _seed_user(schema: str, uid: int, *, email: str | None = None, phone: str | None = None) -> str:
    sid = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO app_user (id, user_no, status, session_version) VALUES (%s, %s, 'active', 1)", (uid, f"U{uid}")
        )
        cur.execute(
            "INSERT INTO user_credential (user_id, username, phone, password_hash, password_configured, status) "
            "VALUES (%s, %s, %s, %s, true, 'active')",
            (uid, f"u_{uid}", phone, hash_password("InitPass!2026")),
        )
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, sid, auth_time) VALUES (%s, %s, 'active', %s, NOW())",
            (uid, uuid.uuid4().hex, sid),
        )
        if email:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'email', %s, NOW(), 'active', 'email')",
                (uid, email),
            )
        if phone:
            cur.execute(
                "INSERT INTO account_contact (user_id, contact_type, normalized_value, verified_at, status, verification_method) "
                "VALUES (%s, 'phone', %s, NOW(), 'active', 'sms')",
                (uid, phone),
            )
    return sid


