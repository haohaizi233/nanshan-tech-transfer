def test_refresh_preserves_sid_and_never_advances_auth_time(pg_schema):
    # 无密码微信新用户首次登录：签发 sid + auth_time
    ext = ExternalIdentity(
        issuer="wechat-mini",
        tenant_id="default",
        external_subject="wx-auth-time-1",
        display_name="WeChat User",
    )
    boot = bootstrap_session(ext)
    at1 = boot["accessToken"]
    rt1 = boot["refreshToken"]
    uid = boot["user"]["userId"]
    claims1 = decode_token(at1)
    sid1 = claims1["sid"]
    auth_time1 = claims1["auth_time"]
    assert sid1
    assert isinstance(auth_time1, int)

    # 模拟真实认证已超过 300s（STEP_UP_RECENT_AUTH_SECONDS=300）
    aged_epoch = int(time.time()) - 420
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        cur.execute(
            "UPDATE auth_session SET auth_time = to_timestamp(%s) WHERE user_id = %s AND sid = %s",
            (aged_epoch, uid, sid1),
        )

    refreshed = refresh_session(rt1)
    at2 = refreshed["accessToken"]
    rt2 = refreshed["refreshToken"]
    claims2 = decode_token(at2)
    assert claims2["sid"] == sid1
    # iat 已刷新为当前时间，但 auth_time 保持历史真实认证时间不推进
    assert claims2["auth_time"] == aged_epoch
    assert claims2["iat"] - claims2["auth_time"] >= 400

    # 即使携带全新 refreshed access token，因 auth_time 超窗，recent_auth 不再可用
    ctx_refreshed = session_context_from_request(_fake_request(at2), uid)
    summary = get_security_summary(
        uid,
        auth_time=ctx_refreshed.auth_time,
        has_sid=bool(ctx_refreshed.sid),
        token_iat=claims2["iat"],
    )
    assert "recent_auth" not in summary["stepUpMethods"]
    with pytest.raises(BizError, match="超过近期安全窗口"):
        issue_step_up_grant(
            uid,
            purpose="bind_email",
            method="recent_auth",
            session_fingerprint=ctx_refreshed.fingerprint_for_purpose("bind_email"),
            session_ctx=ctx_refreshed,
            target_contact="wx1@example.com",
        )

    # 旧 refresh token 不可重放，且第二次正常刷新仍延续同一 sid 与 aged_epoch
    with pytest.raises(BizError) as replay_exc:
        refresh_session(rt1)
    assert replay_exc.value.http_status == 401
    refreshed2 = refresh_session(rt2)
    claims3 = decode_token(refreshed2["accessToken"])
    assert claims3["sid"] == sid1
    assert claims3["auth_time"] == aged_epoch


def test_legacy_null_auth_time_not_fabricated_and_forged_future_time_rejected(pg_schema):
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        cur.execute("INSERT INTO app_user (id, user_no, status) VALUES (501, 'U501', 'active')")
        cur.execute(
            "INSERT INTO user_credential (user_id, username, password_hash, password_configured, status) "
            "VALUES (501, 'wc_legacy', '', false, 'active')"
        )
        cur.execute("INSERT INTO user_profile (user_id, display_name) VALUES (501, 'LegacyWC')")
        cur.execute("INSERT INTO user_role (user_id, role_code) VALUES (501, 'user')")
        rt_legacy, jti_legacy = sign_refresh_token(501)
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, issued_at, expires_at, sid, auth_time) "
            "VALUES (501, %s, 'active', NOW(), NOW() + INTERVAL '7 days', NULL, NULL)",
            (jti_legacy,),
        )

    rotated = refresh_session(rt_legacy)
    claims = decode_token(rotated["accessToken"])
    assert "auth_time" not in claims
    assert "sid" not in claims

    methods = get_available_step_up_methods(501, auth_time=claims.get("auth_time"), has_sid=False)
    assert "recent_auth" not in methods

    # 伪造未来 auth_time（now + 120s）与缺失 sid 均被拒绝
    future_epoch = int(time.time()) + 120
    assert "recent_auth" not in get_available_step_up_methods(501, auth_time=future_epoch, has_sid=True)
    assert "recent_auth" not in get_available_step_up_methods(501, auth_time=int(time.time()), has_sid=False)

    # token 仅含 iat 而无 auth_time 时同样禁止 recent_auth（构造数据库中存在但无 auth_time 的现代会话）
    sid_no_auth_time = str(uuid.uuid4())
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO auth_session (user_id, refresh_jti, status, issued_at, expires_at, sid, auth_time) "
            "VALUES (501, %s, 'active', NOW(), NOW() + INTERVAL '7 days', %s, NULL)",
            (uuid.uuid4().hex, sid_no_auth_time),
        )
    tok_no_auth_time = sign_access_token(501, "U501", ["user"], 1, sid=sid_no_auth_time, auth_time=None)
    ctx_no_auth = session_context_from_request(_fake_request(tok_no_auth_time), 501)
    assert ctx_no_auth is not None and ctx_no_auth.auth_time is None
    with pytest.raises(BizError, match="近期安全窗口"):
        issue_step_up_grant(
            501,
            purpose="bind_email",
            method="recent_auth",
            session_fingerprint=ctx_no_auth.fingerprint_for_purpose("bind_email"),
            session_ctx=ctx_no_auth,
            target_contact="legacy501@example.com",
        )


def test_step_up_grant_survives_refresh_same_session_and_invalidates_on_logout_cross_device_or_disable(pg_schema):
    pwd_hash = hash_password("StrongPass!2026")
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        cur.execute("INSERT INTO app_user (id, user_no, status) VALUES (601, 'U601', 'active')")
        cur.execute(
            "INSERT INTO user_credential (user_id, username, password_hash, password_configured, status) "
            "VALUES (601, 'pwduser601', %s, true, 'active')",
            (pwd_hash,),
        )
        cur.execute("INSERT INTO user_profile (user_id, display_name) VALUES (601, 'Pwd601')")
        cur.execute("INSERT INTO user_role (user_id, role_code) VALUES (601, 'user')")

    sess_a1 = password_login_session("pwduser601", "StrongPass!2026")
    sess_b = password_login_session("pwduser601", "StrongPass!2026")
    ctx_a1 = session_context_from_request(_fake_request(sess_a1["accessToken"]), 601)
    ctx_b = session_context_from_request(_fake_request(sess_b["accessToken"]), 601)
    assert ctx_a1.sid and ctx_b.sid and ctx_a1.sid != ctx_b.sid

    issued = issue_step_up_grant(
        601,
        purpose="bind_email",
        method="password",
        session_fingerprint=ctx_a1.fingerprint_for_purpose("bind_email"),
        session_ctx=ctx_a1,
        current_password="StrongPass!2026",
        target_contact="bind601@example.com",
    )
    grant = issued["stepUpGrant"]

    # 1. 同一逻辑会话 Refresh Rotation 后，原 Step-up Grant 仍有效（仅不推进 auth_time）
    sess_a2 = refresh_session(sess_a1["refreshToken"])
    ctx_a2 = session_context_from_request(_fake_request(sess_a2["accessToken"]), 601)
    assert ctx_a2.sid == ctx_a1.sid
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        # 2. 跨设备会话 B 企图复用会话 A 签发的 Grant 必须失败 403
        with pytest.raises(BizError) as cross_exc:
            validate_step_up_grant(
                cur,
                user_id=601,
                grant_token=grant,
                purpose="bind_email",
                session_fingerprint=ctx_b.fingerprint_for_purpose("bind_email"),
                session_ctx=ctx_b,
                target_contact="bind601@example.com",
                consume=False,
            )
        assert cross_exc.value.http_status == 403

        # 同一会话 A2 未消费校验可通过
        vrow = validate_step_up_grant(
            cur,
            user_id=601,
            grant_token=grant,
            purpose="bind_email",
            session_fingerprint=ctx_a2.fingerprint_for_purpose("bind_email"),
            session_ctx=ctx_a2,
            target_contact="bind601@example.com",
            consume=False,
        )
        assert vrow["status"] == "active"

    # 3. 主动 logout 会话 A 后：会话 A token 与 Grant 全部失效（会话 B 不受单端登出影响）
    logout_session(sess_a2["refreshToken"])
    with pytest.raises(BizError) as mid_exc:
        identity(_fake_request(sess_a2["accessToken"]))
    assert mid_exc.value.http_status == 401

    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        with pytest.raises(BizError) as revoked_exc:
            validate_step_up_grant(
                cur,
                user_id=601,
                grant_token=grant,
                purpose="bind_email",
                session_fingerprint=ctx_a2.fingerprint_for_purpose("bind_email"),
                session_ctx=ctx_a2,
                target_contact="bind601@example.com",
                consume=False,
            )
        assert revoked_exc.value.http_status == 403

    # 4. 在会话 B 重签 Grant 后调用 revoke_all_user_sessions -> Grant 被撤销且旧版本 Token 401
    grant_b = issue_step_up_grant(
        601,
        purpose="bind_email",
        method="password",
        session_fingerprint=ctx_b.fingerprint_for_purpose("bind_email"),
        session_ctx=ctx_b,
        current_password="StrongPass!2026",
        target_contact="bind601b@example.com",
    )["stepUpGrant"]
    revoke_all_user_sessions(601)
    with pytest.raises(BizError) as ver_exc:
        identity(_fake_request(sess_b["accessToken"]))
    assert ver_exc.value.http_status == 401
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        with pytest.raises(BizError):
            validate_step_up_grant(
                cur,
                user_id=601,
                grant_token=grant_b,
                purpose="bind_email",
                session_fingerprint=ctx_b.fingerprint_for_purpose("bind_email"),
                session_ctx=ctx_b,
                target_contact="bind601b@example.com",
                consume=False,
            )

    # 5. 账号被禁用后 Refresh 同步吊销活跃会话与 Grant
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        cur.execute("UPDATE app_user SET status = 'active' WHERE id = 601")
    sess_c = password_login_session("pwduser601", "StrongPass!2026")
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        cur.execute("UPDATE app_user SET status = 'disabled' WHERE id = 601")
    with pytest.raises(BizError) as dis_exc:
        refresh_session(sess_c["refreshToken"])
    assert dis_exc.value.http_status == 401
