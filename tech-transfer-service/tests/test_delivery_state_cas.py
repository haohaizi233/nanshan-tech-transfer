def _seed_challenge(schema: str, uid: int, cid: str, *, status: str = "pending_send", send_state: str = "reserved"):
    with _schema_cursor(PG_DSN, schema, commit=True) as cur:
        cur.execute(
            "INSERT INTO app_user (id, user_no, status) VALUES (%s, %s, 'active') ON CONFLICT DO NOTHING",
            (uid, f"U{uid}"),
        )
        cur.execute(
            "INSERT INTO auth_challenge(id, user_id, purpose, channel, destination_fingerprint, destination_masked, "
            "code_hash, status, attempt_count, max_attempts, expires_at, send_request_id, send_state, code_hash_version) "
            "VALUES (%s, %s, 'password_recovery', 'email_otp', 'fp', 'm', 'h', %s, 0, 5, NOW() + INTERVAL '5 minutes', %s, %s, 2)",
            (cid, uid, status, cid, send_state),
        )


def test_cas_transitions_duplicate_receipt_and_late_receipt_never_revive_terminal_status(pg_schema):
    # 1. reserved -> sending -> accepted + 重复回执幂等
    cid1 = str(uuid.uuid4())
    _seed_challenge(pg_schema, 1, cid1, status="pending_send", send_state="reserved")
    with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
        r1 = transition_delivery_state(cur, cid1, ("reserved",), "sending", provider_name="tencent_ses")
        assert (
            r1.outcome == "transitioned" and r1.current_status == "pending_send" and r1.current_send_state == "sending"
        )
        r2 = transition_delivery_state(
            cur, cid1, ("sending",), "accepted", provider_ids=["mid-1"], provider_name="tencent_ses"
        )
        assert r2.outcome == "transitioned" and r2.current_status == "pending" and r2.current_send_state == "accepted"
        r2_dup = transition_delivery_state(cur, cid1, ("sending",), "accepted")
        assert r2_dup.outcome == "already_target" and r2_dup.updated is False

    # 2. 并发 accepted vs rejected 争夺同一 sending 记录 -> 只有一个成功，不允许合法 accepted 被 rejected 覆盖
    cid2 = str(uuid.uuid4())
    _seed_challenge(pg_schema, 2, cid2, status="pending_send", send_state="sending")
    outcomes = []
    lock = threading.Lock()
    barrier = threading.Barrier(2)

    def _race(target):
        barrier.wait(timeout=5)
        with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
            res = transition_delivery_state(
                cur, cid2, ("sending",), target, provider_ids=["m2"] if target == "accepted" else None
            )
            with lock:
                outcomes.append((target, res.outcome, res.current_send_state))

    t1 = threading.Thread(target=_race, args=("accepted",))
    t2 = threading.Thread(target=_race, args=("rejected",))
    t1.start()
    t2.start()
    t1.join(timeout=10)
    t2.join(timeout=10)
    assert sum(1 for _, out, _ in outcomes if out == "transitioned") == 1
    assert sum(1 for _, out, _ in outcomes if out == "conflict_or_disallowed") == 1

    # 3. 终态防复活：consumed / cancelled / expired / locked 收到延迟回执绝不复活为 pending！
    for term_status, start_send, next_send in (
        ("consumed", "accepted", "delivered"),
        ("cancelled", "sending", "accepted"),
        ("expired", "unknown", "delivered"),
        ("consumed", "accepted", "bounced"),
    ):
        cid_term = str(uuid.uuid4())
        _seed_challenge(pg_schema, 3, cid_term, status=term_status, send_state=start_send)
        with _schema_cursor(PG_DSN, pg_schema, commit=True) as cur:
            res = transition_delivery_state(
                cur,
                cid_term,
                (start_send,),
                next_send,
                challenge_status_on_failure="failed",
            )
            assert res.outcome == "transitioned"
            assert res.current_status == term_status  # 绝不被 CASE 改写回 pending 或 failed！


