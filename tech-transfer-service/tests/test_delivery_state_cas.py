        EMAIL_CODE_TTL_SECONDS=300,
        EMAIL_COOLDOWN_SECONDS=60,
        EMAIL_LIMIT_10M=20,
        EMAIL_LIMIT_1H=50,
        EMAIL_LIMIT_DAY=100,
        EMAIL_IP_LIMIT_1M=50,
        EMAIL_IP_LIMIT_1H=100,
