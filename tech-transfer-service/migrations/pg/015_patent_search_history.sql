-- 015: 专利检索历史（按用户和检索模式隔离，保留最近 10 条由服务层维护）

BEGIN;

CREATE TABLE IF NOT EXISTS public.patent_search_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE ON DELETE CASCADE,
    search_mode VARCHAR(16) NOT NULL CHECK (search_mode IN ('keyword', 'assignee')),
    keyword     VARCHAR(128) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_patent_search_history_user_mode_keyword UNIQUE (user_id, search_mode, keyword)
);

CREATE INDEX IF NOT EXISTS idx_patent_search_history_recent
    ON public.patent_search_history(user_id, search_mode, updated_at DESC, id DESC);

COMMIT;
