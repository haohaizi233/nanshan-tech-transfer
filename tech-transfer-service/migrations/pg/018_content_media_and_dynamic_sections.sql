CREATE TABLE IF NOT EXISTS public.file_object (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_provider VARCHAR(16) NOT NULL DEFAULT 'local',
    storage_key VARCHAR(512) NOT NULL UNIQUE,
    original_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(128) NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    sha256 CHAR(64) NOT NULL,
    width INT DEFAULT NULL,
    height INT DEFAULT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'deleted')),
    created_by BIGINT NOT NULL REFERENCES public.app_user(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ DEFAULT NULL
);
CREATE INDEX IF NOT EXISTS idx_file_object_owner ON public.file_object(created_by, status);
CREATE INDEX IF NOT EXISTS idx_file_object_sha256 ON public.file_object(sha256);

CREATE TABLE IF NOT EXISTS public.achievement_section (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement(id) ON DELETE CASCADE,
    section_code VARCHAR(32) NOT NULL,
    title VARCHAR(128) NOT NULL,
    content TEXT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_achievement_section_code CHECK (section_code IN ('innovation','maturity_detail','project_support','application','tech_problem','tech_method','tech_effect','market_prospect','industrialization','team_intro','technical_route','commercialization','other'))
);
CREATE INDEX IF NOT EXISTS idx_achievement_section_order ON public.achievement_section(achievement_id, sort_order, id);

CREATE TABLE IF NOT EXISTS public.achievement_patent (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement(id) ON DELETE CASCADE,
    patent_no VARCHAR(64) NOT NULL,
    patent_title VARCHAR(500) DEFAULT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    external_url VARCHAR(2048) DEFAULT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_achievement_patent UNIQUE(achievement_id, patent_no)
);
CREATE INDEX IF NOT EXISTS idx_achievement_patent_no ON public.achievement_patent(patent_no);
CREATE INDEX IF NOT EXISTS idx_achievement_patent_order ON public.achievement_patent(achievement_id, sort_order, id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_achievement_primary_patent ON public.achievement_patent(achievement_id) WHERE is_primary;

CREATE TABLE IF NOT EXISTS public.achievement_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement(id) ON DELETE CASCADE,
    link_type VARCHAR(32) NOT NULL,
    label VARCHAR(255) NOT NULL,
    url VARCHAR(2048) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_achievement_link_type CHECK (link_type IN ('official_site','personal_homepage','company_site','demo','video','paper','other'))
);
CREATE INDEX IF NOT EXISTS idx_achievement_link_order ON public.achievement_link(achievement_id, sort_order, id);

CREATE TABLE IF NOT EXISTS public.achievement_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement(id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES public.file_object(id) ON DELETE RESTRICT,
    media_role VARCHAR(16) NOT NULL DEFAULT 'gallery',
    sort_order INT NOT NULL DEFAULT 0,
    caption VARCHAR(500) DEFAULT NULL,
    alt_text VARCHAR(500) DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_achievement_media_role CHECK (media_role IN ('cover','gallery','demo','patent_qr','diagram','product'))
);
CREATE INDEX IF NOT EXISTS idx_achievement_media_order ON public.achievement_media(achievement_id, sort_order, id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_achievement_cover_media ON public.achievement_media(achievement_id) WHERE media_role='cover';

CREATE TABLE IF NOT EXISTS public.demand_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL REFERENCES public.demand(id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES public.file_object(id) ON DELETE RESTRICT,
    attachment_role VARCHAR(16) NOT NULL DEFAULT 'attachment',
    sort_order INT NOT NULL DEFAULT 0,
    caption VARCHAR(500) DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_demand_attachment_role CHECK (attachment_role IN ('attachment','image','specification')),
    CONSTRAINT uk_demand_attachment UNIQUE(demand_id, file_id)
);
CREATE INDEX IF NOT EXISTS idx_demand_attachment_order ON public.demand_attachment(demand_id, sort_order, id);

