CREATE TABLE IF NOT EXISTS notification_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    category VARCHAR(32) NOT NULL CHECK (category IN ('review','cooperation','organization','membership')),
    event_type VARCHAR(64) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    source_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    body TEXT DEFAULT NULL,
    target_path VARCHAR(255) DEFAULT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ DEFAULT NULL,
    dedupe_key VARCHAR(255) NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_notification_inbox_unread ON notification_inbox(recipient_user_id, category, occurred_at DESC) WHERE read_at IS NULL;
