-- ========================================================
-- 002_institution —— 统一机构库（P0-1）
--
-- 来源：nanshan_capital 库三表（MySQL，爬虫只读数据）
--   platform_base      (100 行) -> kind='platform'
--   featured_invest_org (21 行) -> kind='invest'
--   ip_service_org     (16 行) -> kind='service'
--
-- 设计约定（docs/architecture/05-data-model-design.md §8 归并 + 实施计划 P0-1）：
--   - 一表三类（kind 判别），字段语义保留、命名规范化
--   - source_pk 保留源库数值主键：机构类响应 id 与排序第二键
--   - serial_no 保留源站序号：平台类响应 id 与排序键
--   - status 供管理端下架（P0-4），active 对外可见
--   - 幂等可重跑（CREATE IF NOT EXISTS + ETL ON CONFLICT）
-- 迁移后 legacy 三接口改走本表（modules/capital/service.py 适配层），
-- 后端运行时不再依赖 MySQL。
-- ========================================================

-- 22. institution —— 统一机构库
CREATE TABLE IF NOT EXISTS public.institution (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               VARCHAR(16)  NOT NULL,
    name               VARCHAR(255) NOT NULL,
    -- kind=platform 专有（源自 platform_base）
    platform_type      VARCHAR(64)  NOT NULL DEFAULT '',
    platform_type_key  VARCHAR(16)  NOT NULL DEFAULT 'other',
    support_unit       VARCHAR(255) NOT NULL DEFAULT '',
    functions          TEXT         DEFAULT NULL,
    contact_person     VARCHAR(64)  NOT NULL DEFAULT '',
    contact_mobile     VARCHAR(64)  NOT NULL DEFAULT '',
    serial_no          INT          DEFAULT NULL,
    source_status      INT          DEFAULT NULL,
    order_num          INT          DEFAULT NULL,
    -- kind=invest/service 专有（源自 featured_invest_org / ip_service_org）
    intro              TEXT         DEFAULT NULL,
    detail_info        TEXT         DEFAULT NULL,
    label              VARCHAR(64)  NOT NULL DEFAULT '',
    user_type          VARCHAR(64)  NOT NULL DEFAULT '',
    logo_file_id       VARCHAR(64)  NOT NULL DEFAULT '',
    detail_activity_id INT          DEFAULT NULL,
    sort_order         INT          NOT NULL DEFAULT 0,
    -- 跨 kind
    source_pk          INT          DEFAULT NULL,
    source_site        VARCHAR(128) NOT NULL DEFAULT '',
    source_page        VARCHAR(255) NOT NULL DEFAULT '',
    source_api         VARCHAR(255) NOT NULL DEFAULT '',
    fetched_at         TIMESTAMPTZ  DEFAULT NULL,
    status             VARCHAR(16)  NOT NULL DEFAULT 'active',
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_institution_kind CHECK (kind IN ('platform', 'invest', 'service')),
    CONSTRAINT chk_institution_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT uk_institution_source UNIQUE (kind, source_pk)
);

CREATE INDEX IF NOT EXISTS idx_institution_kind_order ON public.institution(kind, sort_order, source_pk);
CREATE INDEX IF NOT EXISTS idx_institution_kind_serial ON public.institution(kind, serial_no);
CREATE INDEX IF NOT EXISTS idx_institution_name ON public.institution(name);
CREATE INDEX IF NOT EXISTS idx_institution_status ON public.institution(status);

COMMENT ON TABLE  public.institution IS '统一机构库（平台/投资机构/专业服务机构），接管 nanshan_capital 三表';
COMMENT ON COLUMN public.institution.kind IS 'platform=概念验证中心/中小试基地, invest=投资机构, service=专业服务机构';
COMMENT ON COLUMN public.institution.platform_type IS '平台类型原文（概念验证中心/中小试基地）';
COMMENT ON COLUMN public.institution.platform_type_key IS '平台类型归一（poc/pilot/other，迁移时由 map_type_key 逻辑计算）';
COMMENT ON COLUMN public.institution.functions IS '平台功能（原 platform_fun）';
COMMENT ON COLUMN public.institution.serial_no IS '源站序号（platform 类排序键与响应 id）';
COMMENT ON COLUMN public.institution.source_pk IS '源库数值主键（机构类排序第二键与响应 id）';
COMMENT ON COLUMN public.institution.source_site IS '数据来源站点';
COMMENT ON COLUMN public.institution.fetched_at IS '源数据抓取时间';
COMMENT ON COLUMN public.institution.status IS 'active=对外可见, disabled=管理端下架';

DROP TRIGGER IF EXISTS trg_institution_updated_at ON public.institution;
CREATE TRIGGER trg_institution_updated_at BEFORE UPDATE ON public.institution
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
