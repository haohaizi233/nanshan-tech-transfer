-- 旧成果写接口曾接收 tags 但未保存。将其升级为独立关系，避免污染主表 JSON 字段。

CREATE TABLE IF NOT EXISTS public.achievement_tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(64) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_achievement_tag_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS public.achievement_tag_relation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement(id) ON DELETE CASCADE ON UPDATE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES public.achievement_tag(id) ON DELETE CASCADE ON UPDATE CASCADE,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_achievement_tag UNIQUE (achievement_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_achievement_tag_relation_tag
    ON public.achievement_tag_relation(tag_id);
