-- ========================================================
-- 004_ai_domain —— AI 任务域（P0-2）
--
-- 本迁移只建“任务边界”所需的表，不实现任何 AI 执行逻辑：
--   ai_task         —— 异步任务队列表（POST /ai/*-tasks 落 queued，
--                      由外部 worker 认领流转，本阶段无 worker）
--   ai_match_result —— 匹配结果表（worker 成功后写入；GET 查询时 JOIN）
--
-- 设计约定（docs/architecture/05-data-model-design.md §7.1/§7.3）：
--   - 状态机 queued/running/succeeded/failed，超时由回收器置 failed
--   - 有状态流转表带乐观锁 version
--   - input_snapshot 固化创建时刻目标数据，input_data_version 为快照哈希
--   - 业务事实必须先落库（不进 Redis）；本阶段任务保持 queued（诚实边界，
--     禁止假 AI 结果回填）
-- ========================================================

-- 23. ai_task —— AI 异步任务
CREATE TABLE IF NOT EXISTS public.ai_task (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type          VARCHAR(32)  NOT NULL,
    status             VARCHAR(16)  NOT NULL DEFAULT 'queued',
    created_by_user_id BIGINT       NOT NULL,
    target_type        VARCHAR(16)  DEFAULT NULL,
    target_id          BIGINT       DEFAULT NULL,
    input_snapshot     JSONB        NOT NULL,
    input_data_version VARCHAR(32)  NOT NULL,
    model_version_id   BIGINT       DEFAULT NULL,
    fail_reason        VARCHAR(500) DEFAULT NULL,
    retry_count        SMALLINT     NOT NULL DEFAULT 0,
    timeout_at         TIMESTAMPTZ  DEFAULT NULL,
    started_at         TIMESTAMPTZ  DEFAULT NULL,
    finished_at        TIMESTAMPTZ  DEFAULT NULL,
    version            INT          NOT NULL DEFAULT 1,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_ai_task_type CHECK (task_type IN ('evaluation', 'match')),
    CONSTRAINT chk_ai_task_status CHECK (status IN ('queued', 'running', 'succeeded', 'failed'))
);

CREATE INDEX IF NOT EXISTS idx_ai_task_queue ON public.ai_task(status, task_type, id);
CREATE INDEX IF NOT EXISTS idx_ai_task_target ON public.ai_task(target_type, target_id);
CREATE INDEX IF NOT EXISTS idx_ai_task_user ON public.ai_task(created_by_user_id, created_at);

COMMENT ON TABLE  public.ai_task IS 'AI 异步任务（评估/匹配）；执行 worker 未接入，任务保持 queued';
COMMENT ON COLUMN public.ai_task.task_type IS 'evaluation=成果评估, match=需求匹配';
COMMENT ON COLUMN public.ai_task.status IS 'queued/running/succeeded/failed（06 §5.4 状态机）';
COMMENT ON COLUMN public.ai_task.input_snapshot IS '创建时刻目标数据快照（防后续编辑导致结果不可解释）';
COMMENT ON COLUMN public.ai_task.input_data_version IS '快照内容 SHA-256 前 16 位';
COMMENT ON COLUMN public.ai_task.timeout_at IS '强制截止时间，超时由回收器置 failed';
COMMENT ON COLUMN public.ai_task.version IS '乐观锁';

DROP TRIGGER IF EXISTS trg_ai_task_updated_at ON public.ai_task;
CREATE TRIGGER trg_ai_task_updated_at BEFORE UPDATE ON public.ai_task
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 24. ai_match_result —— AI 匹配结果（worker 写入，本阶段无数据）
CREATE TABLE IF NOT EXISTS public.ai_match_result (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id          BIGINT      NOT NULL,
    demand_id        BIGINT      NOT NULL,
    achievement_id   BIGINT      NOT NULL,
    score            NUMERIC(5,1) NOT NULL,
    match_reasons    JSONB       DEFAULT NULL,
    model_version_id BIGINT      NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_match UNIQUE (task_id, achievement_id)
);

CREATE INDEX IF NOT EXISTS idx_ai_match_demand ON public.ai_match_result(demand_id, score DESC);

COMMENT ON TABLE  public.ai_match_result IS 'AI 匹配结果（一任务多成果行，worker 成功后写入）';
COMMENT ON COLUMN public.ai_match_result.match_reasons IS '结构化匹配理由数组（替代演示话术）';
