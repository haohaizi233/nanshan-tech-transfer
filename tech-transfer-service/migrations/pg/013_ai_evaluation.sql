-- ========================================================
-- 013_ai_evaluation —— AI 评估结果表（Phase C 非模型基础设施）
--
-- 设计约定（docs/architecture/05-data-model-design.md §7.2）：
--   - 一任务一结果（task_id UNIQUE）
--   - 四维评分 DECIMAL(5,1)：技术特点/应用范围/成熟度/合作可行性
--   - 结果仅由 worker 成功后写入；GET 在 succeeded 时读取组装，
--     queued/running 永远返回 evaluation=null（禁止假评分回填）
--
-- 偏离 05 文档说明：model_version_id 允许 NULL ——
--   ai_model_version 登记机制属于 worker/Provider 接入范畴，本阶段
--   无 worker、无写入方，先收紧非空会导致将来无值可插；
--   worker 接入时补 ai_model_version 表并收紧该列。
-- ========================================================

-- 25. ai_evaluation —— AI 评估结果（worker 写入，本阶段无数据）
CREATE TABLE IF NOT EXISTS public.ai_evaluation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id            BIGINT       NOT NULL,
    achievement_id     BIGINT       NOT NULL,
    score_tech         NUMERIC(5,1) NOT NULL,
    score_application  NUMERIC(5,1) NOT NULL,
    score_maturity     NUMERIC(5,1) NOT NULL,
    score_feasibility  NUMERIC(5,1) NOT NULL,
    total_score        NUMERIC(5,1) NOT NULL,
    summary            TEXT         DEFAULT NULL,
    suggestions        JSONB        DEFAULT NULL,
    model_version_id   BIGINT       DEFAULT NULL,
    input_data_version VARCHAR(32)  NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_eval_task UNIQUE (task_id)
);

CREATE INDEX IF NOT EXISTS idx_ai_eval_ach ON public.ai_evaluation(achievement_id, id);

COMMENT ON TABLE  public.ai_evaluation IS 'AI 评估结果（一任务一结果，worker 成功后写入；本阶段无 worker 无数据）';
COMMENT ON COLUMN public.ai_evaluation.task_id IS 'UNIQUE → ai_task.id（一任务一结果，05 §7.2）';
COMMENT ON COLUMN public.ai_evaluation.score_tech IS '技术特点评分 0-100';
COMMENT ON COLUMN public.ai_evaluation.score_application IS '应用范围评分 0-100';
COMMENT ON COLUMN public.ai_evaluation.score_maturity IS '成熟度评分 0-100';
COMMENT ON COLUMN public.ai_evaluation.score_feasibility IS '合作可行性评分 0-100';
COMMENT ON COLUMN public.ai_evaluation.total_score IS '加权总分 0-100';
COMMENT ON COLUMN public.ai_evaluation.summary IS '评估摘要（前端 conclusion）';
COMMENT ON COLUMN public.ai_evaluation.suggestions IS '结构化建议数组（前端 highlights）';
COMMENT ON COLUMN public.ai_evaluation.model_version_id IS '暂允许 NULL：ai_model_version 登记机制随 worker 接入补齐后收紧（05 §7.4）';
COMMENT ON COLUMN public.ai_evaluation.input_data_version IS '冗余自 ai_task.input_data_version（查询免 JOIN）';
