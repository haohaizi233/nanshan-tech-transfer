-- 020: 可配置的产业目录与成果多对多关联。
-- 不预填不可靠的“20+8”名称；由平台按正式口径维护 industry 后，成果才能选择并筛选。
CREATE TABLE IF NOT EXISTS public.industry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    parent_id BIGINT DEFAULT NULL REFERENCES public.industry(id) ON DELETE RESTRICT,
    sort_order INT NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.achievement_industry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement(id) ON DELETE CASCADE,
    industry_id BIGINT NOT NULL REFERENCES public.industry(id) ON DELETE RESTRICT,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_achievement_industry UNIQUE (achievement_id, industry_id)
);

CREATE INDEX IF NOT EXISTS idx_industry_parent_order ON public.industry(parent_id, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_achievement_industry_order ON public.achievement_industry(achievement_id, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_achievement_industry_industry ON public.achievement_industry(industry_id, achievement_id);
