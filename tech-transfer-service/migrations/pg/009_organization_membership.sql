-- 009_organization_membership.sql
-- Additive organization certification foundation. Existing profile/content data is untouched.

BEGIN;

CREATE TABLE IF NOT EXISTS public.organization_membership (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id              BIGINT       NOT NULL REFERENCES public.organization(id) ON UPDATE CASCADE,
    user_id             BIGINT       NOT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    role                VARCHAR(16)  NOT NULL CHECK (role IN ('member', 'admin')),
    status              VARCHAR(16)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    department          VARCHAR(128) DEFAULT NULL,
    title               VARCHAR(128) DEFAULT NULL,
    verified_by_user_id BIGINT       DEFAULT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    verified_at         TIMESTAMPTZ  DEFAULT NULL,
    revoked_by_user_id  BIGINT       DEFAULT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    revoked_at          TIMESTAMPTZ  DEFAULT NULL,
    revoke_reason       TEXT         DEFAULT NULL,
    version             INT          NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_active_organization_membership
    ON public.organization_membership(user_id, org_id)
    WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_organization_membership_user_status
    ON public.organization_membership(user_id, status);
CREATE INDEX IF NOT EXISTS idx_organization_membership_org_status_role
    ON public.organization_membership(org_id, status, role);

CREATE TABLE IF NOT EXISTS public.organization_membership_application (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    org_id              BIGINT       NOT NULL REFERENCES public.organization(id) ON UPDATE CASCADE,
    real_name           VARCHAR(64)  DEFAULT NULL,
    department          VARCHAR(128) DEFAULT NULL,
    title               VARCHAR(128) DEFAULT NULL,
    work_email          VARCHAR(128) DEFAULT NULL,
    proof_material      TEXT         DEFAULT NULL,
    apply_note          TEXT         DEFAULT NULL,
    status              VARCHAR(16)  NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    reviewed_by_user_id BIGINT       DEFAULT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    reviewed_at         TIMESTAMPTZ  DEFAULT NULL,
    review_reason       TEXT         DEFAULT NULL,
    version             INT          NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pending_organization_membership_application
    ON public.organization_membership_application(user_id, org_id)
    WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_organization_membership_application_org_status_created
    ON public.organization_membership_application(org_id, status, created_at);
CREATE INDEX IF NOT EXISTS idx_organization_membership_application_user_status
    ON public.organization_membership_application(user_id, status);

CREATE TABLE IF NOT EXISTS public.organization_admin_application (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    org_id              BIGINT       NOT NULL REFERENCES public.organization(id) ON UPDATE CASCADE,
    real_name           VARCHAR(64)  DEFAULT NULL,
    department          VARCHAR(128) DEFAULT NULL,
    title               VARCHAR(128) DEFAULT NULL,
    work_email          VARCHAR(128) DEFAULT NULL,
    proof_material      TEXT         DEFAULT NULL,
    reason              TEXT         DEFAULT NULL,
    status              VARCHAR(16)  NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    reviewed_by_user_id BIGINT       DEFAULT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    reviewed_at         TIMESTAMPTZ  DEFAULT NULL,
    review_reason       TEXT         DEFAULT NULL,
    version             INT          NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pending_organization_admin_application
    ON public.organization_admin_application(user_id, org_id)
    WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS public.organization_application (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_user_id   BIGINT       NOT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    requested_name      VARCHAR(128) NOT NULL,
    requested_type      VARCHAR(32)  DEFAULT NULL,
    credit_code         VARCHAR(64)  DEFAULT NULL,
    website             VARCHAR(256) DEFAULT NULL,
    region              VARCHAR(64)  DEFAULT NULL,
    address             VARCHAR(256) DEFAULT NULL,
    contact_name        VARCHAR(64)  DEFAULT NULL,
    contact_phone       VARCHAR(32)  DEFAULT NULL,
    contact_email       VARCHAR(128) DEFAULT NULL,
    proof_material      TEXT         DEFAULT NULL,
    status              VARCHAR(16)  NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    reviewed_by_user_id BIGINT       DEFAULT NULL REFERENCES public.app_user(id) ON UPDATE CASCADE,
    reviewed_at         TIMESTAMPTZ  DEFAULT NULL,
    review_reason       TEXT         DEFAULT NULL,
    version             INT          NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pending_organization_application
    ON public.organization_application(applicant_user_id)
    WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_organization_application_status_created
    ON public.organization_application(status, created_at);

ALTER TABLE public.user_profile
    ADD COLUMN IF NOT EXISTS company_text VARCHAR(128) DEFAULT NULL;
ALTER TABLE public.demand
    ADD COLUMN IF NOT EXISTS org_name_snapshot VARCHAR(128) DEFAULT NULL;

DROP TRIGGER IF EXISTS trg_organization_membership_updated_at ON public.organization_membership;
CREATE TRIGGER trg_organization_membership_updated_at BEFORE UPDATE ON public.organization_membership
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_organization_membership_application_updated_at ON public.organization_membership_application;
CREATE TRIGGER trg_organization_membership_application_updated_at BEFORE UPDATE ON public.organization_membership_application
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_organization_admin_application_updated_at ON public.organization_admin_application;
CREATE TRIGGER trg_organization_admin_application_updated_at BEFORE UPDATE ON public.organization_admin_application
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_organization_application_updated_at ON public.organization_application;
CREATE TRIGGER trg_organization_application_updated_at BEFORE UPDATE ON public.organization_application
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMIT;
