-- ========================================================
-- 033_unified_account_security.sql —— 统一身份认证与账号安全数据模型
--
-- 1. app_user 增加 session_version（会话版本号，用于密码重置后旧 JWT 即时失效）
-- 2. account_contact：经严格确权的安全联系方式（手机号、邮箱），与资料物理分离
-- 3. auth_challenge：统一验证挑战表（验证码/重置链接，HMAC 加盐防篡改，原子消费）
-- 4. recovery_grant：短期密码重置授权凭证（高强度随机数摘要，单次使用，5分钟有效）
-- ========================================================

BEGIN;

-- 1. app_user 增加 session_version
ALTER TABLE public.app_user
    ADD COLUMN IF NOT EXISTS session_version INT NOT NULL DEFAULT 1;

COMMENT ON COLUMN public.app_user.session_version IS '全局会话版本号；密码重置/强制下线时递增，旧 Access Token 即时失效';

-- 2. account_contact：安全联系方式
CREATE TABLE IF NOT EXISTS public.account_contact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_user(id) ON DELETE CASCADE,
    contact_type VARCHAR(16) NOT NULL, -- 'phone' | 'email'
    normalized_value VARCHAR(128) NOT NULL, -- E.164 规范化手机号或规范化邮箱
    verified_at TIMESTAMPTZ DEFAULT NULL, -- 确权通过时间；NULL 表示未验证
    status VARCHAR(16) NOT NULL DEFAULT 'active', -- 'active' | 'revoked'
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ DEFAULT NULL
);

COMMENT ON TABLE public.account_contact IS '用户确权安全联系方式（仅 verified_at 且 active 者可用于找回密码）';
COMMENT ON COLUMN public.account_contact.contact_type IS '联系方式类型：phone 或 email';
COMMENT ON COLUMN public.account_contact.normalized_value IS '规范化联系方式值（统一小写/去空）';
COMMENT ON COLUMN public.account_contact.verified_at IS '验证确权时间戳，未验证不可用于恢复';

-- 部分唯一索引：同一有效手机号不能同时归属于多个有效用户
CREATE UNIQUE INDEX IF NOT EXISTS uk_account_contact_verified_phone
    ON public.account_contact (normalized_value)
    WHERE contact_type = 'phone' AND status = 'active' AND verified_at IS NOT NULL;

-- 部分唯一索引：同一有效邮箱不能同时归属于多个有效用户
CREATE UNIQUE INDEX IF NOT EXISTS uk_account_contact_verified_email
    ON public.account_contact (normalized_value)
    WHERE contact_type = 'email' AND status = 'active' AND verified_at IS NOT NULL;

-- 每个用户某种联系方式最多保留一条 active 记录
CREATE UNIQUE INDEX IF NOT EXISTS uk_account_contact_user_active_type
    ON public.account_contact (user_id, contact_type)
    WHERE status = 'active';

CREATE INDEX IF NOT EXISTS idx_account_contact_user_status
    ON public.account_contact (user_id, status);

DROP TRIGGER IF EXISTS trg_account_contact_updated_at ON public.account_contact;
CREATE TRIGGER trg_account_contact_updated_at BEFORE UPDATE ON public.account_contact
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 3. auth_challenge：统一认证验证挑战
CREATE TABLE IF NOT EXISTS public.auth_challenge (
    id UUID PRIMARY KEY,
    user_id BIGINT DEFAULT NULL REFERENCES public.app_user(id) ON DELETE CASCADE,
    purpose VARCHAR(32) NOT NULL, -- 'password_recovery' | 'bind_phone' | 'bind_email' | 'register'
    channel VARCHAR(16) NOT NULL, -- 'sms' | 'email_otp' | 'email_link'
    destination_fingerprint VARCHAR(64) NOT NULL, -- 联系方式盲索引（HMAC-SHA256 摘要，不可逆检索）
    destination_masked VARCHAR(64) NOT NULL, -- 脱敏展示值（如 138****1234，用于审计与回显）
    code_hash VARCHAR(128) NOT NULL, -- 服务端密钥参与的 HMAC 摘要
    status VARCHAR(16) NOT NULL DEFAULT 'pending', -- 'pending' | 'verified' | 'consumed' | 'expired' | 'failed'
    attempt_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 5,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.auth_challenge IS '认证挑战表（OTP / 一次性重置链接，HMAC 加盐与原子核销）';
COMMENT ON COLUMN public.auth_challenge.purpose IS '挑战目的：password_recovery/bind_phone/bind_email/register';
COMMENT ON COLUMN public.auth_challenge.destination_fingerprint IS '目标联系方式的不可逆检索摘要';
COMMENT ON COLUMN public.auth_challenge.code_hash IS 'HMAC-SHA256 安全验证码摘要';

CREATE INDEX IF NOT EXISTS idx_auth_challenge_dest_pending
    ON public.auth_challenge (destination_fingerprint, purpose, status, expires_at);

CREATE INDEX IF NOT EXISTS idx_auth_challenge_user_id
    ON public.auth_challenge (user_id);

DROP TRIGGER IF EXISTS trg_auth_challenge_updated_at ON public.auth_challenge;
CREATE TRIGGER trg_auth_challenge_updated_at BEFORE UPDATE ON public.auth_challenge
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 4. recovery_grant：短期重置授权凭证
CREATE TABLE IF NOT EXISTS public.recovery_grant (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_user(id) ON DELETE CASCADE,
    challenge_id UUID NOT NULL REFERENCES public.auth_challenge(id) ON DELETE CASCADE,
    grant_hash VARCHAR(128) NOT NULL, -- 客户端持有一次性明文 token 的 SHA256 摘要
    status VARCHAR(16) NOT NULL DEFAULT 'active', -- 'active' | 'consumed' | 'revoked' | 'expired'
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.recovery_grant IS '短期密码恢复授权（高熵随机数单次凭证，默认5分钟有效）';
COMMENT ON COLUMN public.recovery_grant.grant_hash IS '授权凭证 SHA-256 摘要';

CREATE UNIQUE INDEX IF NOT EXISTS uk_recovery_grant_hash
    ON public.recovery_grant (grant_hash);

CREATE INDEX IF NOT EXISTS idx_recovery_grant_user_status
    ON public.recovery_grant (user_id, status);

DROP TRIGGER IF EXISTS trg_recovery_grant_updated_at ON public.recovery_grant;
CREATE TRIGGER trg_recovery_grant_updated_at BEFORE UPDATE ON public.recovery_grant
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 5. 存量用户兼容性回填检查（仅针对现有 user_credential.phone 已经完成短信/微信注册确权的记录安全回填）
-- 遵循设计原则：user_profile.phone/email 绝不自动提升为 verified；
-- 仅对 user_credential 中已具备登录资格且唯一的 11 位 phone 予以安全初始化。
INSERT INTO public.account_contact (user_id, contact_type, normalized_value, verified_at, status)
SELECT uc.user_id, 'phone', uc.phone, uc.created_at, 'active'
FROM public.user_credential uc
JOIN public.app_user au ON au.id = uc.user_id
WHERE uc.phone IS NOT NULL
  AND uc.phone ~ '^\d{11}$'
  AND uc.status = 'active'
  AND au.status = 'active'
  AND au.deleted_at IS NULL
  AND NOT EXISTS (
      SELECT 1 FROM public.account_contact ac
      WHERE ac.user_id = uc.user_id AND ac.contact_type = 'phone'
  )
  AND NOT EXISTS (
      SELECT 1 FROM public.account_contact ac2
      WHERE ac2.normalized_value = uc.phone AND ac2.contact_type = 'phone' AND ac2.status = 'active'
  )
ON CONFLICT DO NOTHING;

COMMIT;
